def selftest():
    assert num(0.000301) == r"\num{3.01e-4}", num(0.000301)
    assert num(137.4) == r"\num{137}", num(137.4)
    assert num(1.234, 2) == r"\num{1.2}", num(1.234, 2)
    assert num(12345678) == r"\num{1.23e7}", num(12345678)
    assert num(32777, 2) == r"\num{33000}", num(32777, 2)
    assert num(9.98e6, 2) == r"\num{1.0e7}", num(9.98e6, 2)
    assert num(0.0299, 2) == r"\num{0.030}", num(0.0299, 2)
    assert integer("150525") == r"\num{150525}"
    assert listing(["a", "b", "c"]) == "a, b and c" and listing(["a"]) == "a" and listing([]) == ""
    assert float32_ulp(1.0) == 2.0 ** -23
    assert float32_ulp(0.0098) == 2.0 ** -30, float32_ulp(0.0098)
    try:
        macro("bad1", "x")
        raise AssertionError("a digit in a macro name was accepted")
    except ValueError:
        pass
    keys = [k for _, _, _, k in CONFIGS] + [k for _, _, k in CASES]
    assert len(keys) == len(set(keys)) and all(k.isalpha() for k in keys)
    # The tables and figures are built from the committed data, so the data must be complete.
    index = summary_index(read_csv("summary.csv"))
    for r in index.values():
        assert r["qp_per_iteration_median"], r
    assert len(read_csv("agreement.csv")) == len(CASES) * (len(CONFIGS) - 1)
    assert {r["case"] for r in read_csv("ab.csv")} == set(CASE_LABEL)
    precision_index(read_csv("precision.csv"))
    assert len(read_csv("precision_runs.csv")) == len(CASES) * len(PRECISION_CONFIGS) * 2 * 3
    # Per configuration: double's repeats 2 and 3 and single's 1 to 3 against double's first.
    assert len(read_csv("precision_agreement.csv")) == len(CASES) * len(PRECISION_CONFIGS) * 5
    nccl_index(read_csv("nccl.csv"))
    assert len(read_csv("nccl_runs.csv")) == len(CASES) * len(NCCL_CONFIGS) * 2 * 3
    release_index(read_csv("release_runs.csv"))
    assert len(read_csv("release_runs.csv")) == len(CASES) * len(RELEASE_RULES) * len(RELEASE_STEPS) * 3
    # The pump strokes: every run and change, the stills on disk, and the events the text names.
    strokes, history = transient_runs(), transient_history()
    transient_ablation()
    transient_failures(strokes)
    for n in STILLS:
        for view, _ in STILL_VIEWS:
            path = os.path.join(HERE, "..", "figures", "stills", "%05d_%s.png" % (n, view))
            assert os.path.isfile(path), path
        assert n < len(history["final"]), n
    for run, _, _ in ALL_RUNS:
        assert len(history[run]) == int(strokes[run]["steps"]) + 1, run
    # The refined stills at the times of FF200's, to a step.
    for a, b in zip(STILLS, STILLS_REFINED):
        assert abs(history["final"][a]["t"] - history["refined"][b]["t"]) <= max(history["refined"][b]["dt"], 1e-12), (a, b)
        for view in ("overview", "pressure_valve", "suction_valve"):
            path = os.path.join(HERE, "..", "figures", "stills_refined", "%05d_%s.png" % (b, view))
            assert os.path.isfile(path), path
    # Open over [5, 21) ms in stroke 1; [50, 53) and, longer, [60, 71) ms in stroke 2.
    rows = [{"t": i * 1e-3, "u": 1e-3 if 5 <= i <= 20 or 50 <= i <= 52 or 60 <= i <= 70 else 0.0}
            for i in range(91)]
    e = valve_events(rows, "u", 1)
    assert [round(x["open"] * 1e3) for x in e] == [5, 60] and [round(x["close"] * 1e3) for x in e] == [21, 71], e
    assert round(e[1]["rebound"] * 1e3) == 3 and e[0]["rebound"] == 0, e
    # The history's storage: every run the tables name, and the diagnostics' counts.
    prony = prony_index(read_csv("prony_runs.csv"))
    for set_name, _, _ in VALVE_SETS:
        assert lookup(prony, set_name, "full", repeat=True), set_name
        assert lookup(prony, set_name, "int16_scaled", s32=True), set_name
    for fmt, s32 in VALVE_ROWS:
        assert lookup(prony, "FF200_TET4", fmt, s32=s32), (fmt, s32)
        if fmt != "full":
            assert lookup(prony, "FF200_TET4", fmt, plain=True, s32=s32) or s32, (fmt, s32)
    for s, _, _ in TORSION_SETS + TORSION_COARSE:
        for fmt in ["full_b"] + REDUCED_FORMATS + [f + "_plain" for f in REDUCED_FORMATS]:
            assert (s, fmt) in prony, (s, fmt)
    diag = prony_index(read_csv("prony_diag.csv"))
    assert all(int(r["updates"]) > 0 for r in diag.values())
    b = bench_index(read_csv("prony_bench.csv"))
    for fmt, _ in HISTORY_FORMATS:
        for space in ("host", "device"):
            for e, q, _ in BENCH_SHAPES:
                for horizon in ("0", BENCH_HORIZON):
                    assert (fmt, space, e, q, horizon) in b, (fmt, space, e, q, horizon)
    print("ldp_figures selftest passed")


