def num(x, digits=3):
    """x to `digits` significant digits as siunitx input."""
    if x == 0:
        return r"\num{0}"
    mantissa, e = ("%.*e" % (digits - 1, x)).split("e")
    e = int(e)
    if -3 <= e < 6:
        return r"\num{%.*f}" % (max(0, digits - 1 - e), float("%se%d" % (mantissa, e)))
    return r"\num{%se%d}" % (mantissa, e)


def integer(x):
    return r"\num{%d}" % int(round(float(x)))


def listing(names):
    """a, b and c."""
    names = list(names)
    return ", ".join(names[:-1]) + " and " + names[-1] if len(names) > 1 else "".join(names)


def macro(name, value):
    if not name.isalpha():
        raise ValueError("TeX macro names take letters only: %s" % name)
    return "\\newcommand{\\%s}{%s}\n" % (name, value)


def float32_ulp(x):
    """The spacing of float32 numbers at |x|."""
    if x == 0:
        return 2.0 ** -149
    f = struct.unpack("<f", struct.pack("<f", abs(x)))[0]
    return 2.0 ** (math.frexp(f)[1] - 24)


def precision_index(rows):
    """(case, config, storage_bytes) -> row, failing on a missing or duplicated one."""
    index = {}
    for r in rows:
        key = (r["case"], r["config"], r["storage_bytes"])
        if key in index:
            sys.exit("ldp_figures: %s appears twice in precision.csv" % (key,))
        index[key] = r
    for case, _, _ in CASES:
        for config, _, _ in PRECISION_CONFIGS:
            for b in ("8", "4"):
                if (case, config, b) not in index:
                    sys.exit("ldp_figures: precision.csv has no %s %s in %s bytes" % (case, config, b))
    return index


def nccl_index(rows):
    """(case, config, nodes, communication) -> row, failing on a missing or duplicated one."""
    index = {}
    for r in rows:
        key = (r["case"], r["config"], r["nodes"], r["communication"])
        if key in index:
            sys.exit("ldp_figures: %s appears twice in nccl.csv" % (key,))
        index[key] = r
    for case, _, _ in CASES:
        for config, nodes, _, _ in NCCL_CONFIGS:
            for c in ("mpi", "nccl"):
                if (case, config, nodes, c) not in index:
                    sys.exit("ldp_figures: nccl.csv has no %s %s on %s node(s) by %s" % (case, config, nodes, c))
    return index


def release_index(rows):
    """(case, rule, pseudo-steps) -> its runs, failing on a missing, failed or unconverged run."""
    index = {}
    for r in rows:
        if r["config"] != "host_4x72":
            sys.exit("ldp_figures: release_runs.csv has a run on %s; the text says 4 x 72" % r["config"])
        if r["rc"] != "0" or not float(r["final"]) <= 1e-8:
            sys.exit("ldp_figures: release run %s %s n=%s r%s failed or did not converge"
                     % (r["case"], r["rule"], r["pseudo_steps"], r["repeat"]))
        index.setdefault((r["case"], r["rule"], r["pseudo_steps"]), []).append(r)
    for case, _, _ in CASES:
        for rule, _ in RELEASE_RULES:
            for n in RELEASE_STEPS:
                if len(index.get((case, rule, n), [])) != 3:
                    sys.exit("ldp_figures: release_runs.csv lacks repeats of %s %s n=%s" % (case, rule, n))
    return index


def release_solve(runs):
    return statistics.median(float(r["solve"]) for r in runs)


def release_newton(runs):
    """Newton iterations of every attempt, a cut-back's included."""
    return statistics.median(int(r["newton"]) + int(r["failed_newton"]) for r in runs)


def to_solution(r):
    """Set-up and solve: the time to solution with the set-up NCCL's adds to."""
    return float(r["setup_median"]) + solve_time(r)


def per_iteration(r):
    return float(r["qp_per_iteration_median"])


def nccl_setup(a, b):
    """What NCCL's set-up costs a run once, measured: the set-up it lengthens (NCCL's own runs
    beside it, on a thread) and the wait at the first communication (s); a by MPI, b by NCCL."""
    return float(b["setup_median"]) - float(a["setup_median"]) + float(b["nccl_wait_median"])


def nccl_break_even(a, b):
    """The QP iterations a process needs to repay nccl_setup, None if NCCL saves nothing."""
    saved = 1e-6 * (per_iteration(a) - per_iteration(b))
    return nccl_setup(a, b) / saved if saved > 0 else None


def solve_time(r):
    return float(r["solve_median"])


