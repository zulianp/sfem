def table_cases(index, utopia):
    u = {r["case"]: r for r in utopia}
    lines = [PREAMBLE,
             r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
             r"Case & Elements & Dofs & Contact nodes & \multicolumn{2}{c}{Newton steps} \\",
             r"\cmidrule(l){5-6}",
             r" & & & & SFEM & utopia \\", r"\midrule"]
    for case, label, _ in CASES:
        r = index[(case, "host_1x72", "1")]
        lines.append("%s & %s & %s & %s & %s & %s \\\\" % (
            label, integer(r["elements"]), integer(r["dofs"]), integer(r["contact_nodes"]),
            integer(r["newton"]), integer(u[case]["newton"])))
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_accuracy(ab, kkt):
    k = {}
    for r in kkt:
        if r["state"] == "sfem" or r["grid"] == "legacy":
            k[(r["case"], r["state"])] = float(r["residual"])
    a = {r["case"]: r for r in ab}
    lines = [PREAMBLE,
             r"\begin{tabular}{@{}lrrrrrrr@{}}", r"\toprule",
             r" & \multicolumn{2}{c}{$\|u_S-u_U\|/\|u_U\|$ (\%)} & \multicolumn{2}{c}{$\max \phi$ (\si{\metre})}"
             r" & \multicolumn{2}{c}{KKT measure} & \\",
             r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
             r"Case & max & $\ell_2$ & SFEM & utopia & SFEM & utopia & Jaccard \\", r"\midrule"]
    for case, label, _ in CASES:
        r = a[case]
        lines.append("%s & %s & %s & %s & %s & %s & %s & %s \\\\" % (
            label, num(100 * float(r["rel_max_diff"]), 2), num(100 * float(r["rel_l2_diff"]), 2),
            num(float(r["max_sdf_sfem"]), 2), num(float(r["max_sdf_utopia"]), 2),
            num(k[(case, "sfem")], 2), num(k[(case, "utopia")], 2), num(float(r["contact_jaccard"]), 3)))
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_performance(index):
    head = " & ".join(r"\multicolumn{2}{c}{%s}" % label for _, label, _ in CASES)
    rules = "".join(r"\cmidrule(lr){%d-%d}" % (3 + 2 * i, 4 + 2 * i) for i in range(len(CASES)))
    lines = [PREAMBLE,
             r"\begin{tabular}{@{}ll" + "rr" * len(CASES) + "@{}}", r"\toprule",
             r" & & " + head + r" \\", rules,
             r"Nodes & Configuration & " + " & ".join([r"\si{\micro\second}", r"\si{\second}"] * len(CASES))
             + r" \\", r"\midrule"]
    group = None
    for config, nodes, label, _ in CONFIGS:
        kind = ("Grace" if config.startswith("host") else "GPU", nodes)
        if group is not None and kind != group:
            lines.append(r"\addlinespace")
        group = kind
        cells = []
        for case, _, _ in CASES:
            r = index[(case, config, nodes)]
            cells += [integer(per_iteration(r)), num(solve_time(r), 3)]
        lines.append("%s & %s & %s \\\\" % (nodes, label, " & ".join(cells)))
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


