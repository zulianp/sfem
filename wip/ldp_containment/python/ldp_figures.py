def read_csv(name):
    with open(os.path.join(DATA, name), newline="") as f:
        return list(csv.DictReader(f))


def read_machine():
    machine, gpus = {}, []
    for line in open(os.path.join(DATA, "machine.txt")):
        if "=" not in line:
            continue
        k, v = line.rstrip("\n").split("=", 1)
        if k == "gpu":
            gpus.append([x.strip() for x in v.split(",")])
        else:
            machine[k] = v
    machine["gpus"] = gpus
    return machine


def summary_index(rows):
    """(case, config, nodes) -> row, failing on a missing or duplicated configuration."""
    index = {}
    for r in rows:
        key = (r["case"], r["config"], r["nodes"])
        if key in index:
            sys.exit("ldp_figures: %s appears twice in summary.csv" % (key,))
        index[key] = r
    for case, _, _ in CASES:
        for config, nodes, _, _ in CONFIGS:
            if (case, config, nodes) not in index:
                sys.exit("ldp_figures: summary.csv has no %s %s on %s node(s)" % (case, config, nodes))
    return index


