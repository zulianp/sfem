def macros(index, runs, agreement, ab, kkt, newton, utopia, coords, machine, precision, precision_runs,
           precision_agreement, nccl, nccl_runs, omp_regions, team_cost, release_runs):
    out = [PREAMBLE]
    m = lambda name, value: out.append(macro(name, value))

    # The machine and the software
    m("machineCPU", machine["cpu"])
    m("machineModules", machine["sockets"])
    m("machineCores", machine["cores_per_socket"])
    m("machineHostMemory", r"\SI{%s}{\giga\byte}" % machine["host_memory_gb"])
    name, mem, driver = machine["gpus"][0][1], machine["gpus"][0][2], machine["gpus"][0][3]
    m("machineGPU", name.replace("NVIDIA ", ""))
    m("machineGPUMemory", r"\SI{%.0f}{\gibi\byte}" % (float(mem.split()[0]) / 1024))
    m("machineDriver", driver)
    m("machineCUDA", machine["cuda"])
    m("machineGCC", machine["gcc"])
    m("machineMPICH", machine["mpich"])
    m("machineLibfabric", machine["libfabric"])

    # The protocol
    repeats = {r["repeats"] for r in index.values()}
    if len(repeats) != 1:
        sys.exit("ldp_figures: configurations have different repeat counts %s" % sorted(repeats))
    m("benchRepeats", repeats.pop())
    m("benchRuns", integer(len(runs)))
    m("benchFailed", integer(sum(r["rc"] != "0" for r in runs)))
    spread = {key: (float(r["qp_per_iteration_max"]) - float(r["qp_per_iteration_min"])) / per_iteration(r)
              for key, r in index.items()}
    worst = max(spread, key=spread.get)
    m("benchSpread", num(100 * spread[worst], 2))
    m("benchSpreadMedian", num(100 * statistics.median(spread.values()), 2))
    label = {(c, n): lab for c, n, lab, _ in CONFIGS}[(worst[1], worst[2])]
    m("benchSpreadWhere", "%s, %s%s" % (CASE_LABEL[worst[0]], label, " on 2 nodes" if worst[2] == "2" else ""))

    # The cases
    for case, _, key in CASES:
        r = index[(case, "host_1x72", "1")]
        m("elements" + key, integer(r["elements"]))
        m("dofs" + key, integer(r["dofs"]))
        m("contact" + key, integer(r["contact_nodes"]))
        m("newton" + key, integer(r["newton"]))
        m("qp" + key, integer(r["qp_iterations"]))
        its = [int(r["qp_iterations"]) for r in index.values() if r["case"] == case]
        m("qpSpread" + key, num(100 * (max(its) - min(its)) / min(its), 2))
    spreads = []
    for case, _, _ in CASES:
        its = [int(r["qp_iterations"]) for r in index.values() if r["case"] == case]
        spreads.append((max(its) - min(its)) / min(its))
    m("qpSpreadMax", num(100 * max(spreads), 2))
    dofs = [int(index[(c, "host_1x72", "1")]["dofs"]) for c, _, _ in CASES]
    m("dofsMin", integer(min(dofs)))
    m("dofsMax", integer(max(dofs)))
    m("dofsRatio", num(max(dofs) / min(dofs), 2))
    converged = [c for c, _, _ in CASES if float(index[(c, "host_1x72", "1")]["final"]) <= CONVERGED]
    unconverged = [c for c, _, _ in CASES if c not in converged]
    m("convergedCases", listing(CASE_LABEL[c] for c in converged) or "none")
    m("unconvergedCases", listing(CASE_LABEL[c] for c in unconverged) or "none")
    m("convergedTol", num(CONVERGED, 1))
    capped = [r for r in newton if int(r["qp_iterations"]) >= QP_CAP]
    m("qpCap", integer(QP_CAP))
    m("qpCapped", integer(len(capped)))
    # What the single-process runs' QP solves do at the cap, as a clause.
    if capped:
        m("qpCappedClause", "%s QP solves stop at the iteration cap (%s); the Newton iteration continues "
          "from the capped increment" % (integer(len(capped)), ", ".join(sorted({CASE_LABEL[r["case"]] for r in capped}))))
    else:
        m("qpCappedClause", "no QP solve reaches the iteration cap of %s" % integer(QP_CAP))

    # Agreement between configurations (last displacement, against 1 x 72): the converged cases,
    # and apart the ones whose Newton budget ends first, whose state depends on where each inexact
    # QP stopped.
    serial = [r for r in agreement if r["config"] == "gpu_1" and r["case"] in converged]
    parallel = [r for r in agreement if r["config"] != "gpu_1" and r["case"] in converged]
    rest = [r for r in agreement if r["case"] not in converged]
    rel = lambda r: float(r["max_du"]) / float(r["max_u"])
    m("agreeSerial", num(max(rel(r) for r in serial), 2))
    m("agreeParallel", num(max(rel(r) for r in parallel), 2))
    m("agreeParallelAbs", num(max(float(r["max_du"]) for r in parallel), 2))
    if rest:
        m("agreeUnconverged", num(max(rel(r) for r in rest), 2))
        m("finalUnconverged", listing(num(float(index[(c, "host_1x72", "1")]["final"]), 2)
                                      for c in unconverged))
    m("coordUlp", num(min(float32_ulp(max(abs(float(c["min"])), abs(float(c["max"]))))
                          for c in coords), 2))
    m("coordUlpMax", num(max(float32_ulp(max(abs(float(c["min"])), abs(float(c["max"]))))
                             for c in coords), 2))

    # Against utopia
    for r in ab:
        key = CASE_KEY[r["case"]]
        m("abRelMax" + key, num(100 * float(r["rel_max_diff"]), 2))
        m("abRelL" + key, num(100 * float(r["rel_l2_diff"]), 2))
    m("abPenUtopiaMax", num(max(float(r["max_sdf_utopia"]) for r in ab), 2))
    m("abSdfSfemMax", num(max(float(r["max_sdf_sfem"]) for r in ab), 2))
    m("abJaccardMin", num(min(float(r["contact_jaccard"]) for r in ab), 3))
    measure = {}
    for r in kkt:
        if r["state"] == "sfem":
            m("kktSfem" + CASE_KEY[r["case"]], num(float(r["residual"]), 2))
            measure.setdefault(r["case"], {})["sfem"] = float(r["residual"])
        elif r["grid"] == "legacy":
            m("kktUtopia" + CASE_KEY[r["case"]], num(float(r["residual"]), 2))
            measure.setdefault(r["case"], {})["utopia"] = float(r["residual"])
    ratios = [measure[c]["utopia"] / measure[c]["sfem"] for c in converged]
    if ratios:
        m("kktRatioMin", num(min(ratios), 2))
        m("kktRatioMax", num(max(ratios), 2))
    grids = {}
    for r in kkt:
        if r["state"] == "utopia":
            grids.setdefault(r["case"], {})[r["grid"]] = float(r["residual"])
    m("kktGridChange", num(100 * max(abs(g["sdf"] - g["legacy"]) / g["legacy"] for g in grids.values()), 1))

    # Utopia's timers
    for r in utopia:
        key = CASE_KEY[r["case"]]
        m("utopiaTime" + key, num(float(r["total"]), 3))
        m("utopiaNewton" + key, integer(r["newton"]))
    m("utopiaRanks", integer(utopia[0]["ranks"]))

    # Performance
    for case, _, key in CASES:
        for config, nodes, _, ckey in CONFIGS:
            r = index[(case, config, nodes)]
            m("it" + key + ckey, integer(per_iteration(r)))
            m("t" + key + ckey, num(solve_time(r), 3))
        best = min(CONFIGS, key=lambda c: solve_time(index[(case, c[0], c[1])]))
        m("best" + key, best[2] + (" on 2 nodes" if best[1] == "2" else ""))
        m("bestTime" + key, num(solve_time(index[(case, best[0], best[1])]), 3))
        grace = min((c for c in CONFIGS if c[0].startswith("host")),
                    key=lambda c: solve_time(index[(case, c[0], c[1])]))
        gpu = min((c for c in CONFIGS if c[0].startswith("gpu")),
                  key=lambda c: solve_time(index[(case, c[0], c[1])]))
        m("gpuOverGrace" + key, num(solve_time(index[(case, grace[0], grace[1])]) /
                                    solve_time(index[(case, gpu[0], gpu[1])]), 2))
        m("qpShare" + key, num(100 * min(float(index[(case, c[0], c[1])]["qp_median"]) /
                                         solve_time(index[(case, c[0], c[1])]) for c in CONFIGS), 2))
    bests, gains = [], []
    for case, _, _ in CASES:
        rs = [index[(case, c[0], c[1])] for c in CONFIGS]
        bests.append(min(per_iteration(r) for r in rs))
        grace = min(solve_time(r) for r in rs if r["kind"] == "host")
        gpu = min(solve_time(r) for r in rs if r["kind"] == "gpu")
        gains.append(grace / gpu)
    m("itBestMin", integer(min(bests)))
    m("itBestMax", integer(max(bests)))
    m("gpuOverGraceMin", num(min(gains), 2))
    m("gpuOverGraceMax", num(max(gains), 2))
    fastest = {c: min(CONFIGS, key=lambda k: solve_time(index[(c, k[0], k[1])])) for c, _, _ in CASES}
    one_gpu = [CASE_LABEL[c] for c, _, _ in CASES if fastest[c][0] == "gpu_1"]
    m("oneGpuBestCases", listing(one_gpu) or "none")
    # The other cases and their fastest configuration, as a clause.
    others = [(CASE_LABEL[c], fastest[c][2] + (" on 2 nodes" if fastest[c][1] == "2" else ""))
              for c, _, _ in CASES if fastest[c][0] != "gpu_1"]
    if not others:
        sys.exit("ldp_figures: one GPU is the fastest everywhere: the text says otherwise")
    m("bestElsewhere", ("on %s it is %s" if len(others) == 1 else "on %s the fastest are %s, respectively")
      % (listing(o for o, _ in others), listing(b for _, b in others)))
    # The abstract: several GPUs fastest on the largest mesh; on the others one GPU is the fastest
    # GPU configuration and the fastest Grace configuration solves close to it (within 25%).
    largest = max(CASES, key=lambda c: int(index[(c[0], CONFIGS[0][0], CONFIGS[0][1])]["dofs"]))[0]
    if fastest[largest][0] in ("gpu_1",) or not fastest[largest][0].startswith("gpu"):
        sys.exit("ldp_figures: several GPUs are no longer the fastest on the largest mesh")
    close = []
    for c, _, _ in CASES:
        if c == largest:
            continue
        best = lambda kind: min((k for k in CONFIGS if k[0].startswith(kind)),
                                key=lambda k: solve_time(index[(c, k[0], k[1])]))
        if best("gpu")[0] != "gpu_1":
            sys.exit("ldp_figures: one GPU is not the fastest GPU configuration on " + c)
        a, b = (solve_time(index[(c, k[0], k[1])]) for k in (best("host"), best("gpu")))
        close.append(100 * (max(a, b) / min(a, b) - 1))
    if max(close) > 25:
        sys.exit("ldp_figures: Grace and one GPU are no longer close on the smaller meshes")
    m("graceGpuCloseMax", integer(max(close)))
    ratio = lambda case, a, b: per_iteration(index[(case,) + a]) / per_iteration(index[(case,) + b])
    slower = [c for c, _, _ in CASES if ratio(c, ("host_4x72", "1"), ("host_1x72", "1")) > 1]
    least = min(CASES, key=lambda c: int(index[(c[0], "host_1x72", "1")]["dofs"]))[0]
    if slower != [least]:
        sys.exit("ldp_figures: 4x72 is slower than 1x72 on %s: the text says only on the case with "
                 "the least work per rank" % slower)
    m("fourSlowerThanOneCases", listing(CASE_LABEL[c] for c in slower))
    threads = [ratio(c, ("host_4x72", "1"), ("host_16x18", "1")) for c, _, _ in CASES]
    m("hostThreadsMin", num(min(threads), 2))
    m("hostThreadsMax", num(max(threads), 2))
    # OpenMP on Grace: an empty region with 72 and with 18 threads per rank (as much as a pass over
    # a rank's unknowns), the regions a QP iteration of FF200 on 1x72 opens, and the stand-in CG
    # step (team_cost.c) on FF200's unknowns: a region per pass with reduction clauses against one
    # region with chunk sums (256 chunks, as the solver on these sizes), on 1x72 and 4x72. Its
    # synchronisation accounts for most of what 4x72 adds to FF200's iteration over 1x72.
    region = {(r["ranks"], r["threads"]): float(r["empty_us"]) for r in omp_regions if r["kind"] == "cost"}
    for r in omp_regions:
        if r["kind"] == "cost" and abs(float(r["sweep_us"]) / float(r["empty_us"]) - 1) > 0.25:
            sys.exit("ldp_figures: a pass over a rank's unknowns no longer costs about an empty region")
    count = [r for r in omp_regions if r["kind"] == "count"]
    per_it = int(count[0]["regions"]) / int(count[0]["qp_iterations"])
    if per_it >= 1:
        sys.exit("ldp_figures: a QP iteration opens %.2f regions: the text says its CG steps share one" % per_it)
    standin = {(r["ranks"], r["threads"]): r for r in team_cost if r["n"] == "150525" or
               (r["ranks"], r["n"]) == ("4", "37631")}
    one, four = standin[("1", "72")], standin[("4", "72")]
    added = float(four["chunk256_us"]) - float(one["chunk256_us"])
    gap = per_iteration(index[(least, "host_4x72", "1")]) - per_iteration(index[(least, "host_1x72", "1")])
    if not gap / 2 < added <= gap:
        sys.exit("ldp_figures: the stand-in's synchronisation adds %.0f us of %s's %.0f us between "
                 "4x72 and 1x72: the text says most of it" % (added, least, gap))
    m("regionCostWide", num(region[("4", "72")], 2))
    m("regionCostNarrow", num(region[("16", "18")], 2))
    m("regionsPerIteration", num(per_it, 2))
    m("standinRegionsOne", integer(float(one["regions_us"])))
    m("standinRegionsFour", integer(float(four["regions_us"])))
    m("standinTeamOne", integer(float(one["chunk256_us"])))
    m("standinTeamFour", integer(float(four["chunk256_us"])))
    m("standinGap", integer(added))
    m("hostGapOneFour", integer(gap))

    # The tangent in single precision against double, per configuration
    m("precisionRuns", integer(len(precision_runs)))
    if any(r["rc"] != "0" for r in precision_runs):
        sys.exit("ldp_figures: a precision run failed")
    gains = {}
    for case, _, _ in CASES:
        for config, _, _ in PRECISION_CONFIGS:
            d, s = precision[(case, config, "8")], precision[(case, config, "4")]
            if d["newton"] != s["newton"]:
                sys.exit("ldp_figures: %s %s takes %s Newton steps in double, %s in single"
                         % (case, config, d["newton"], s["newton"]))
            gains[(case, config)] = 1 - per_iteration(s) / per_iteration(d)
    m("singleMax", num(100 * max(gains.values()), 2))
    one_gpu = [gains[(c, "gpu_1")] for c, _, _ in CASES]
    m("singleGpuOneMin", num(100 * min(one_gpu), 2))
    m("singleGpuOneMax", num(100 * max(one_gpu), 2))
    refined = "FF200_mesh_refined"
    m("solveDoubleFFfGpuOne", num(solve_time(precision[(refined, "gpu_1", "8")]), 3))
    m("solveSingleFFfGpuOne", num(solve_time(precision[(refined, "gpu_1", "4")]), 3))
    m("singleRefinedGrace", num(100 * gains[(refined, "host_16x18")], 2))
    m("singleRefinedFour", num(100 * gains[(refined, "gpu_4")], 2))
    # Elsewhere (several ranks on the smaller cases) the change, negative where single is faster.
    small = [-gains[(c, k)] for c, _, _ in CASES for k, _, _ in PRECISION_CONFIGS if k != "gpu_1" and c != refined]
    m("singleSmallMin", num(100 * min(small), 2))
    m("singleSmallMax", num(100 * max(small), 2))
    # QP iterations: the change of the median between precisions against the spread between the
    # repeats of double, per configuration; the text names the configurations where the change is
    # the larger, and by how much.
    its = {}
    for r in precision_runs:
        its.setdefault((r["case"], r["config"], r["storage_bytes"]), []).append(int(r["qp_iterations"]))
    changes, excess = [], []
    for case, _, _ in CASES:
        for config, _, _ in PRECISION_CONFIGS:
            d, s = its[(case, config, "8")], its[(case, config, "4")]
            change = abs(statistics.median(s) / statistics.median(d) - 1)
            spread = (max(d) - min(d)) / min(d)
            changes.append(change)
            if change > spread:
                excess.append(change - spread)
    if not excess:
        sys.exit("ldp_figures: single changes the QP iterations within double's spread everywhere: "
                 "the text says otherwise")
    m("singleQpChange", num(100 * max(changes), 2))
    m("singleQpConfigs", integer(len(changes)))
    m("singleQpOutside", integer(len(excess)))
    m("singleQpExcess", num(100 * max(excess), 2))
    # Displacements: single against double, and double against itself, in the same configuration
    rel = lambda r: float(r["max_du"]) / float(r["max_u"])
    for group, cases in (("", converged), ("Unconverged", unconverged)):
        if not cases:
            continue
        single = [rel(r) for r in precision_agreement if r["case"] in cases and r["storage_bytes"] == "4"]
        double = [rel(r) for r in precision_agreement if r["case"] in cases and r["storage_bytes"] == "8"]
        m("agreeSingle" + group, num(max(single), 2))
        m("agreeDouble" + group, num(max(double), 2))

    # Communication within a node by NCCL against MPI
    m("ncclRuns", integer(len(nccl_runs)))
    if any(r["rc"] != "0" for r in nccl_runs):
        sys.exit("ldp_figures: an NCCL comparison run failed")
    change = {}
    for case, _, _ in CASES:
        for config, nodes, _, _ in NCCL_CONFIGS:
            a, b = nccl[(case, config, nodes, "mpi")], nccl[(case, config, nodes, "nccl")]
            if a["newton"] != b["newton"]:
                sys.exit("ldp_figures: %s %s takes %s Newton steps by MPI, %s by NCCL" % (case, config, a["newton"], b["newton"]))
            change[(case, config, nodes)] = per_iteration(b) / per_iteration(a) - 1
    # The change per QP iteration, as a gain (NCCL faster) or a loss, whichever the text states.
    for config, nodes, _, key in NCCL_CONFIGS:
        c = [change[(case, config, nodes)] for case, _, _ in CASES]
        if max(c) < 0:
            m("nccl" + key + "GainMin", num(-100 * max(c), 2))
            m("nccl" + key + "GainMax", num(-100 * min(c), 2))
        elif min(c) > 0:
            m("nccl" + key + "LossMin", num(100 * min(c), 2))
            m("nccl" + key + "LossMax", num(100 * max(c), 2))
        else:
            m("nccl" + key + "ChangeMin", num(100 * min(c), 2))
            m("nccl" + key + "ChangeMax", num(100 * max(c), 2))
    # What NCCL's set-up costs once, measured (nccl_setup), its own time on its thread, the time
    # to solution it adds, and the QP iterations a process needs to repay it.
    init, extra, cost, even = [], [], [], []
    for case, _, _ in CASES:
        for config, nodes, _, _ in NCCL_CONFIGS:
            a, b = nccl[(case, config, nodes, "mpi")], nccl[(case, config, nodes, "nccl")]
            init.append(float(b["nccl_init_median"]))
            extra.append(to_solution(b) - to_solution(a))
            cost.append(nccl_setup(a, b))
            even.append(nccl_break_even(a, b))
    if min(extra) <= 0:
        sys.exit("ldp_figures: NCCL no longer lengthens a solution; the text says it does")
    if None in even:
        sys.exit("ldp_figures: NCCL saves nothing per QP iteration somewhere; the text says it repays its set-up")
    m("ncclInitMin", num(min(init), 2))
    m("ncclInitMax", num(max(init), 2))
    m("ncclExtraMin", num(min(extra), 2))
    m("ncclExtraMax", num(max(extra), 2))
    m("ncclCostMin", num(min(cost), 2))
    m("ncclCostMax", num(max(cost), 2))
    m("ncclBreakEvenMin", integer(1000 * round(min(even) / 1000)))
    m("ncclBreakEvenMax", integer(1000 * round(max(even) / 1000)))

    # The overlap released over pseudo-steps (release_runs.csv)
    rel = release_index(release_runs)
    m("releaseRepeats", integer(3))
    if any(r["cutbacks"] != "0" for r in release_runs if r["rule"] == "damped"):
        sys.exit("ldp_figures: a damped release run cut back; the text says none did")
    two, four, per_step = [], [], []
    for case, _, _ in CASES:
        t = [release_solve(rel[(case, "damped", n)]) for n in RELEASE_STEPS]
        if not t[0] < t[1] < t[2]:
            sys.exit("ldp_figures: on %s more damped pseudo-steps are not slower: %s" % (case, t))
        two.append(t[1] / t[0])
        four.append(t[2] / t[0])
        one = release_newton(rel[(case, "damped", "1")])
        per_step += [release_newton(rel[(case, "damped", n)]) / int(n) / one for n in RELEASE_STEPS[1:]]
    if not (0.8 <= min(per_step) and max(per_step) <= 1.25):
        sys.exit("ldp_figures: a damped pseudo-step no longer takes about the single step's Newton "
                 "iterations: %.2f to %.2f" % (min(per_step), max(per_step)))
    m("releaseTwoMin", num(min(two), 2))
    m("releaseTwoMax", num(max(two), 2))
    m("releaseFourMin", num(min(four), 2))
    m("releaseFourMax", num(max(four), 2))
    m("releasePerStepMin", num(min(per_step), 2))
    m("releasePerStepMax", num(max(per_step), 2))
    cut = [c for c, _, _ in CASES if any(r["cutbacks"] != "0" for r in rel[(c, "armijo", "1")])]
    if len(cut) != 1 or not all(r["cutbacks"] != "0" for r in rel[(cut[0], "armijo", "1")]):
        sys.exit("ldp_figures: the text names one case whose single Armijo step cuts back in every "
                 "repeat: %s" % cut)
    damped = {c: release_solve(rel[(c, "damped", "1")]) for c, _, _ in CASES}
    armijo = {c: release_solve(rel[(c, "armijo", "1")]) for c, _, _ in CASES}
    faster = [c for c, _, _ in CASES if armijo[c] < damped[c]]
    if set(faster) != set(CASE_LABEL) - set(cut):
        sys.exit("ldp_figures: the single Armijo step is faster on %s, not on every case without a "
                 "cut-back" % faster)
    gain = [100 * (1 - armijo[c] / damped[c]) for c in faster]
    m("armijoFasterCases", listing(CASE_LABEL[c] for c in faster))
    m("armijoGainMin", num(min(gain), 2))
    m("armijoGainMax", num(max(gain), 2))
    m("armijoCutbackCase", CASE_LABEL[cut[0]])
    m("armijoCutbackSlower", num(armijo[cut[0]] / damped[cut[0]], 2))
    armijo_runs = [r for r in release_runs if r["rule"] == "armijo"]
    m("armijoRuns", integer(len(armijo_runs)))
    m("armijoCutbackRuns", integer(sum(r["cutbacks"] != "0" for r in armijo_runs)))
    return "".join(out)


