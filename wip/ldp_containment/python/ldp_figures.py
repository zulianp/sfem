def table_performance(index):
    head = " & ".join(r"\multicolumn{2}{c}{%s}" % label for _, label, _ in CASES)
    rules = "".join(r"\cmidrule(lr){%d-%d}" % (3 + 2 * i, 4 + 2 * i) for i in range(len(CASES)))
    lines = [PREAMBLE,
             r"\begin{tabular}{@{}ll" + "rr" * len(CASES) + "@{}}", r"\toprule",
             r" & & " + head + r" \\", rules,
             r"Nodes & Configuration & " + " & ".join([r"\si{\micro\second}", r"\si{\second}"] * len(CASES))
             + r" \\", r"\midrule"]
    group = None
    for config, nodes, label, _ in CONFIGS:
        kind = ("Grace" if config.startswith("host") else "GPU", nodes)
        if group is not None and kind != group:
            lines.append(r"\addlinespace")
        group = kind
