def colors():
    hexes = ["4C72B0", "DD8452", "55A868", "C44E52"]
    return PREAMBLE + "".join("\\definecolor{%s}{HTML}{%s}\n" % (n, h) for n, h in zip(COLORS, hexes))


def figure_per_iteration(index):
    """Grouped bars: time per QP iteration of every configuration, one bar per case."""
    coords = ["c%d" % i for i in range(len(CONFIGS))]
    ticks = ",".join(r"{%s%s}" % (label, r"\\2 nodes" if nodes == "2" else "")
                     for _, nodes, label, _ in CONFIGS)
    out = [PREAMBLE,
           r"\begin{tikzpicture}",
           r"\begin{axis}[ybar, bar width=3.2pt, width=\textwidth, height=5.2cm,",
           r"  symbolic x coords={%s}, xtick=data," % ",".join(coords),
           r"  xticklabels={%s}, xticklabel style={font=\scriptsize, align=center}," % ticks,
           r"  ymin=0, ylabel={\si{\micro\second} per QP iteration}, ymajorgrids,",
           r"  legend style={font=\scriptsize, at={(0.5,1.02)}, anchor=south, legend columns=4},",
           r"  enlarge x limits=0.06]"]
    for (case, label, _), color in zip(CASES, COLORS):
        pts = " ".join("(%s,%.1f)" % (c, per_iteration(index[(case, config, nodes)]))
                       for c, (config, nodes, _, _) in zip(coords, CONFIGS))
        dofs = index[(case, "host_1x72", "1")]["dofs"]
        out.append(r"\addplot[fill=%s, draw=none] coordinates {%s};" % (color, pts))
        out.append(r"\addlegendentry{%s (\num{%s} dofs)}" % (label, dofs))
    out += [r"\end{axis}", r"\end{tikzpicture}"]
    return "\n".join(out) + "\n"


def figure_breakdown(index, case):
    """Stacked bars: where the solve time of one case goes, per configuration."""
    parts = [("QP exchange", lambda r: f(r, "exchange_begin") + f(r, "exchange_wait")),
             ("QP other", lambda r: f(r, "qp") - f(r, "exchange_begin") - f(r, "exchange_wait")),
             ("Assembly", lambda r: f(r, "assemble")),
             ("Other", lambda r: f(r, "solve") - f(r, "qp") - f(r, "assemble"))]
    coords = ["c%d" % i for i in range(len(CONFIGS))]
    ticks = ",".join(r"{%s%s}" % (label, r"\\2 nodes" if nodes == "2" else "")
                     for _, nodes, label, _ in CONFIGS)
    out = [PREAMBLE,
           r"\begin{tikzpicture}",
           r"\begin{axis}[ybar stacked, bar width=7pt, width=\columnwidth, height=5.0cm,",
           r"  symbolic x coords={%s}, xtick=data," % ",".join(coords),
           r"  xticklabels={%s}, xticklabel style={font=\tiny, align=center}," % ticks,
           r"  ymin=0, ylabel={time to solution (\si{\second})}, ymajorgrids,",
           r"  legend style={font=\scriptsize, at={(0.5,1.02)}, anchor=south, legend columns=2},",
           r"  enlarge x limits=0.07]"]
    for (name, value), color in zip(parts, COLORS):
        pts = " ".join("(%s,%.3f)" % (c, max(0.0, value(index[(case, config, nodes)])))
                       for c, (config, nodes, _, _) in zip(coords, CONFIGS))
        out.append(r"\addplot[fill=%s, draw=none] coordinates {%s};" % (color, pts))
        out.append(r"\addlegendentry{%s}" % name)
    out += [r"\end{axis}", r"\end{tikzpicture}"]
    return "\n".join(out) + "\n"


def f(r, key):
    return float(r[key + "_median"] or 0)


