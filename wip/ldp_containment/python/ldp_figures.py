#!/usr/bin/env python3
"""Tables, figures and number macros of the valve-containment report, from ../data.

Stdlib only, like the repository's other report generators: the Alps uenv has no numpy or
matplotlib, and a generator that cannot run where the measurements are taken goes stale.

Inputs (../data, copied from the jobs that produced them; README.md names the jobs):
  summary.csv, runs.csv   workflows/ldp_containment/python/collect.py over the benchmark
  agreement.csv           each configuration's last displacement against the 1 x 72 run
  ab.csv                  workflows/ldp_containment/python/ab_utopia.py, 1 x 72 against utopia
  kkt.csv                 the KKT measure at utopia's and at SFEM's final state
  newton.csv              Newton residuals and QP iterations of the 1 x 72 runs
  utopia.csv              utopia's own timers (summary.8.0.csv), 8 ranks, machine unknown
  coordinates.csv         the meshes' coordinate ranges (their float32 resolution)
  machine.txt             the node and the software, key=value

Usage:
    python3 ldp_figures.py --out ../figures --tables ../tables
    python3 ldp_figures.py --selftest
"""

import argparse
import csv
import math
import os
import statistics
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")

PREAMBLE = ("%% Generated by wip/ldp_containment/python/ldp_figures.py -- do not edit.\n"
            "%% Regenerate with: make figures\n")

# The cases in order of size, with the names the text uses and the letters their macros carry
# (TeX control words take letters only).
CASES = [
    ("FF200_ExodusMesh", "FF200", "FFc"),
    ("FP70_similar_coarse", "FP70 coarse", "FPc"),
    ("FP70_similar", "FP70", "FPf"),
    ("FF200_mesh_refined", "FF200 refined", "FFf"),
]
CASE_LABEL = {c: label for c, label, _ in CASES}
CASE_KEY = {c: key for c, _, key in CASES}

# The configurations in the order of the tables and figures: (config, nodes, label, macro key).
CONFIGS = [
    ("host_1x72", "1", r"$1\times72$", "HostOne"),
    ("host_4x72", "1", r"$4\times72$", "HostFour"),
    ("host_16x18", "1", r"$16\times18$", "HostSixteen"),
    ("host_4x72", "2", r"$4\times72$", "HostFourTwo"),
    ("host_8x72", "2", r"$8\times72$", "HostEight"),
    ("host_32x18", "2", r"$32\times18$", "HostThirtyTwo"),
    ("gpu_1", "1", "1 GPU", "GpuOne"),
    ("gpu_4", "1", "4 GPUs", "GpuFour"),
    ("gpu_4", "2", "4 GPUs", "GpuFourTwo"),
    ("gpu_8", "2", "8 GPUs", "GpuEight"),
]
COLORS = ["LdpA", "LdpB", "LdpC", "LdpD"]
QP_CAP = 15000
# A run whose last Newton residual is this far below the first counts as converged.
CONVERGED = 1e-6


# ---------------------------------------------------------------------------------------------
# Reading
# ---------------------------------------------------------------------------------------------

def read_csv(name):
    with open(os.path.join(DATA, name), newline="") as f:
        return list(csv.DictReader(f))


def read_machine():
    machine, gpus = {}, []
    for line in open(os.path.join(DATA, "machine.txt")):
        if "=" not in line:
            continue
        k, v = line.rstrip("\n").split("=", 1)
        if k == "gpu":
            gpus.append([x.strip() for x in v.split(",")])
        else:
            machine[k] = v
    machine["gpus"] = gpus
    return machine


def summary_index(rows):
    """(case, config, nodes) -> row, failing on a missing or duplicated configuration."""
    index = {}
    for r in rows:
        key = (r["case"], r["config"], r["nodes"])
        if key in index:
            sys.exit("ldp_figures: %s appears twice in summary.csv" % (key,))
        index[key] = r
    for case, _, _ in CASES:
        for config, nodes, _, _ in CONFIGS:
            if (case, config, nodes) not in index:
                sys.exit("ldp_figures: summary.csv has no %s %s on %s node(s)" % (case, config, nodes))
    return index


