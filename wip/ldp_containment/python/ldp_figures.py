import csv
import math
import os
import statistics
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")

PREAMBLE = ("%% Generated by wip/ldp_containment/python/ldp_figures.py -- do not edit.\n"
            "%% Regenerate with: make figures\n")

# The cases in order of size, with the names the text uses and the letters their macros carry
# (TeX control words take letters only).
CASES = [
    ("FF200_ExodusMesh", "FF200", "FFc"),
    ("FP70_similar_coarse", "FP70 coarse", "FPc"),
    ("FP70_similar", "FP70", "FPf"),
    ("FF200_mesh_refined", "FF200 refined", "FFf"),
]
CASE_LABEL = {c: label for c, label, _ in CASES}
CASE_KEY = {c: key for c, _, key in CASES}

# The configurations in the order of the tables and figures: (config, nodes, label, macro key).
CONFIGS = [
    ("host_1x72", "1", r"$1\times72$", "HostOne"),
    ("host_4x72", "1", r"$4\times72$", "HostFour"),
    ("host_16x18", "1", r"$16\times18$", "HostSixteen"),
    ("host_8x72", "2", r"$8\times72$", "HostEight"),
    ("host_32x18", "2", r"$32\times18$", "HostThirtyTwo"),
    ("gpu_1", "1", "1 GPU", "GpuOne"),
    ("gpu_4", "1", "4 GPUs", "GpuFour"),
    ("gpu_8", "2", "8 GPUs", "GpuEight"),
]
# The configurations of the precision comparison: (config, label, macro key).
PRECISION_CONFIGS = [
    ("host_16x18", r"$16\times18$", "HostSixteen"),
    ("gpu_1", "1 GPU", "GpuOne"),
    ("gpu_4", "4 GPUs", "GpuFour"),
]
# The configurations of the NCCL comparison: (config, nodes, label, macro key).
NCCL_CONFIGS = [
    ("gpu_4", "1", "4 GPUs", "One"),
    ("gpu_8", "2", "8 GPUs, 2 nodes", "Eight"),
]
# The release comparison: the line-search rules (rule, label) and the numbers of pseudo-steps.
RELEASE_RULES = [("damped", "damped"), ("armijo", "Armijo")]
RELEASE_STEPS = ["1", "2", "4"]
COLORS = ["LdpA", "LdpB", "LdpC", "LdpD"]
QP_CAP = 15000
# A run whose last Newton residual is this far below the first counts as converged.
CONVERGED = 1e-6


