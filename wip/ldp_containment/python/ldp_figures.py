#!/usr/bin/env python3
"""Tables, figures and number macros of the valve-containment report, from ../data.

Stdlib only, like the repository's other report generators: the Alps uenv has no numpy or
matplotlib, and a generator that cannot run where the measurements are taken goes stale.

Inputs (../data, copied from the jobs that produced them; README.md names the jobs):
  summary.csv, runs.csv   workflows/ldp_containment/python/collect.py over the benchmark
  agreement.csv           each configuration's last displacement against the 1 x 72 run
  ab.csv                  workflows/ldp_containment/python/ab_utopia.py, 1 x 72 against utopia
  kkt.csv                 the KKT measure at utopia's and at SFEM's final state
  newton.csv              Newton residuals and QP iterations of the 1 x 72 runs
  utopia.csv              utopia's own timers (summary.8.0.csv), 8 ranks, machine unknown
  coordinates.csv         the meshes' coordinate ranges (their float32 resolution)
  precision.csv, precision_runs.csv
                          the tangent in double and in single precision (storage_bytes 8, 4),
                          alternating per repeat on one node, same columns as summary/runs
  precision_agreement.csv each such run's last displacement against the same configuration's
                          first double run
  nccl.csv, nccl_runs.csv GPU configurations with the communication within a node by MPI and by
                          NCCL (nccl: true), alternating per repeat, same columns as summary/runs
  omp_regions.csv         workflows/ldp_containment/omp: an empty OpenMP region per run shape and
                          the regions FF200's QP iterations open on 1 x 72
  team_cost.csv           workflows/ldp_containment/omp/team_cost.c: a stand-in CG step, a region
                          per pass against one region with fixed-chunk sums, per run shape
  release_runs.csv        the overlap released over 1, 2 and 4 quasi-static pseudo-steps, each
                          converged, with the damped and the Armijo line search, on 4 x 72,
                          alternating per repeat, same columns as runs.csv
  machine.txt             the node and the software, key=value
  transient_runs.csv, transient_ablation.csv, transient_history.csv
                          FF200 through four pump strokes on one GPU per time integrator, and over
                          the first 16 or 30 ms one change at a time (python/collect_transient.py)
  fp70_membrane_pressure.csv
                          the chamber pressure driving them (workflows/ldp_containment/transient)

Usage:
    python3 ldp_figures.py --out ../figures --tables ../tables
    python3 ldp_figures.py --selftest
"""

