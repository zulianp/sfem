JF_NAME = {
    "jac_exact":  "Jacobian action, exact",
    "jac_lagged": "Jacobian action, lagged",
    "spmv_f64":   r"SpMV, lagged \texttt{f64}",
    "spmv_f32":   r"SpMV, lagged \texttt{f32}",
}


def parse_jacfair(path):
    out = []
    for line in open(path):
        f = line.split()
        if len(f) >= 4 and f[0] in JF_NAME and f[2] != "-":
            try:
                out.append((f[0], f[1], float(f[2])))
            except ValueError:
                continue
    return out


def table_jacfair(rows):
    """Matrix-free against the assembled matrix, with the operators made comparable.

    The exact row is what a Newton--Krylov solve should apply; the lagged row is the operator
    the assembled matrix can hold, and is the one to compare with the SpMV rows. Reporting only
    the exact row against the SpMV would understate the matrix-free side, because it would be
    doing strictly more work than the matrix encodes.
    """
    if not rows:
        return None
    by = {}
    for op, lay, v in rows:
        by.setdefault(op, {})[lay] = v
    out = [PREAMBLE, r"\small", r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
           r"operator & packed & atomic & vs.\ \texttt{f64} \\",
           r"& \multicolumn{2}{c}{MDOF/s} & \\", r"\midrule"]
    f64 = by.get("spmv_f64", {}).get("none")
    for op in ("jac_exact", "jac_lagged"):
        if op not in by:
            continue
        pk, at = by[op].get("packed"), by[op].get("atomic")
        rel = (r"$%.2f\times$" % (pk / f64)) if pk and f64 else "---"
        out.append(r"%s & %.0f & %.0f & %s \\" % (JF_NAME[op], pk or 0, at or 0, rel))
    out.append(r"\midrule")
    for op in ("spmv_f64", "spmv_f32"):
        v = by.get(op, {}).get("none")
        if v is None:
            continue
        rel = (r"$%.2f\times$" % (v / f64)) if f64 else "---"
        out.append(r"%s & \multicolumn{2}{c}{%.0f} & %s \\" % (JF_NAME[op], v, rel))
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


def macros_jacfair(rows):
    by = {}
    for op, lay, v in rows:
        by.setdefault(op, {})[lay] = v
    out = [PREAMBLE]
    ex = by.get("jac_exact", {}).get("packed")
    lg = by.get("jac_lagged", {}).get("packed")
    f64 = by.get("spmv_f64", {}).get("none")
    f32 = by.get("spmv_f32", {}).get("none")
    if ex and lg:
        out.append(r"\newcommand{\jfExactCost}{%.2f}" % (lg / ex))
    if lg and f64:
        out.append(r"\newcommand{\jfLaggedVsF}{%.2f}" % (lg / f64))
    if lg and f32:
        out.append(r"\newcommand{\jfLaggedVsS}{%.2f}" % (lg / f32))
    if ex and f64:
        # The ratio the UNFAIR comparison would have produced, quoted in the paper to show how
        # much the mismatch was worth rather than silently corrected.
        out.append(r"\newcommand{\jfExactVsF}{%.2f}" % (ex / f64))
    la = by.get("jac_lagged", {}).get("atomic")
    if la and f64:
        out.append(r"\newcommand{\jfLaggedAtomicVsF}{%.2f}" % (la / f64))
    return "\n".join(out) + "\n"


