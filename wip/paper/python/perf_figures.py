def read_campaign(path):
    """Rows of a layout-campaign CSV, as dicts, with the numeric fields converted.

    REFUSES A CSV SPANNING SEVERAL HOSTS. The tables below keep the best reading per
    configuration, so across two nodes a packed row and the atomic row it is divided by can come
    from different machines, which manufactures a layout ratio out of node-to-node variation
    (5-11% here). The campaign appends to its csv and the batch jobs once wrote into a fixed
    directory, so this is a situation that has actually arisen, not a hypothetical.
    """
    import csv as _csv
    with open(path) as fh:
        rows = list(_csv.DictReader(fh))
    hosts = sorted({r.get("host", "?") for r in rows})
    if len(hosts) > 1:
        raise ValueError("campaign spans %d hosts (%s); split it by host before plotting"
                         % (len(hosts), ", ".join(hosts)))
    out = []
    for r in rows:
        try:
            r["_n"] = int(r["cube_n"])
            r["_dofs"] = int(r["dofs"])
            r["_mdof"] = float(r["MDOF_s"])
        except (KeyError, ValueError):
            continue
        out.append(r)
    return out, (hosts[0] if hosts else "?")


def _bare(r):
    """The bare element kernel: no solver terms carried."""
    return (r.get("ran_rc") == "off" and r.get("ran_boundary") == "off"
            and r.get("transient") in ("0", "", None)
            and r.get("pgrad_per_apply") in ("0", "", None))


def best(rows, **eq):
    """Best observed rate among rows matching every keyword.

    Best rather than mean, because background load can only make a run slower -- the same
    convention the repository's own kernel report uses.
    """
    sel = [r for r in rows if all(r.get(k) == v for k, v in eq.items())]
    return max((r["_mdof"] for r in sel), default=None)


def fig_throughput(rows, host, op="residual"):
    """F5. Throughput against problem size for the three representations.

    The assembled matrix is drawn at both storage precisions because halving the value width is
    essentially the only lever a bandwidth-bound SpMV has, and it is the fairest version of the
    comparison.
    """
