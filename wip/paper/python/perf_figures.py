# Widths the format fixes, named here so the arithmetic below can be read against the code.
PACK_IDX_BYTES = 2    # pack_idx_t is uint16_t; this is what bounds a pack's node count
GLOBAL_IDX_BYTES = 4  # idx_t in the flat connectivity and in the BSR column index
GEOM_BYTES = 4        # geom_t is float
NODES_PER_ELEM = 8    # HEX8
BLOCK = 4             # 4x4 blocks: three velocity components and pressure


def footprint_rows(csv_path):
    """Bytes per degree of freedom for the representations the paper compares.

    THIS IS NOT A TIMING, which is why it may be taken from an older campaign. Every quantity
    below is a deterministic function of the mesh size and the storage precision -- the row
    count, the block count, the index widths -- so it does not inherit the node-to-node
    variation that makes two campaigns' THROUGHPUTS incomparable. The distinction is worth
    making explicitly, because the rule against mixing campaigns is otherwise absolute.

    Counted on both sides: only what the apply must read to evaluate the operator. Solution
    and result vectors are excluded from both, since they are identical for every layout and
    including them would flatter the matrix.
    """
    rows = {}
    with open(csv_path) as fh:
        head = fh.readline().rstrip("\n").split(",")
        ix = {name: i for i, name in enumerate(head)}
        for line in fh:
            f = line.rstrip("\n").split(",")
            if len(f) != len(head) or f[ix["operation"]] != "bsr_apply":
                continue
            n = int(f[ix["cube_n"]])
            store = f[ix["bsr_storage"]]
            key = (n, store)
            if key in rows:
                continue
            dofs = int(f[ix["dofs"]])
            nodes = int(f[ix["nodes"]])
            elems = int(f[ix["elements"]])
            blocks = int(f[ix["bsr_nnz"]])
            vals = float(f[ix["bsr_values_MiB"]]) * 1024 * 1024
            # The matrix also carries its pattern: one column index per block, one row pointer
            # per block row. Omitting it would understate the matrix by ~3%.
            idx = blocks * GLOBAL_IDX_BYTES + (nodes + 1) * GLOBAL_IDX_BYTES
            # The matrix-free side reads the mesh: pack-local connectivity and coordinates.
            conn = elems * NODES_PER_ELEM * PACK_IDX_BYTES
            coords = nodes * 3 * GEOM_BYTES
            rows[key] = {
                "n": n, "store": store, "dofs": dofs,
                "bsr": (vals + idx) / dofs,
                "packed": (conn + coords) / dofs,
            }
    return [rows[k] for k in sorted(rows)]


def parse_meshfoot(path):
    """Read the bench's --mesh-footprint report: {pack_size: {array: bytes}} plus counts.

    This replaces an earlier arithmetic model of the same quantity, which is why there is no
    model left to compare against. The model had to guess the two numbers that decide the
    answer -- how many ghost entries the packs produce and how many rows the reduction graph
    has -- because neither has a closed form: they depend on how the pack boundaries happen to
    cut the mesh. It guessed both from the mean node count per pack and was wrong by about
    20%. The bench now reports every array's own nbytes(), so this parser reads measurements.
    """
    out, cur = {}, None
    for line in open(path):
        line = line.strip()
        if line.startswith("@@@ pack_size"):
            cur = int(line.split()[-1])
            out[cur] = {"arrays": {}}
        elif cur is None:
            continue
        elif line.startswith("### mesh footprint"):
            for k in ("n_nodes", "n_elements", "dofs"):
                m = re.search(k + r"=(\d+)", line)
                if m:
                    out[cur][k] = int(m.group(1))
        elif line.startswith("### n_packs"):
            for k in ("n_packs", "ghost_entries", "ghost_reduce_rows"):
                m = re.search(k + r"=(\d+)", line)
                if m:
                    out[cur][k] = int(m.group(1))
        else:
            f = line.split()
            if len(f) == 3 and ("." in f[0]) and f[1].isdigit():
                out[cur]["arrays"][f[0]] = int(f[1])
    return {k: v for k, v in out.items() if v.get("dofs") and v["arrays"]}


# The pack size the paper reports the footprint at: the shipped default, so the table describes
# the format as a user gets it. The alternative -- quoting the best-performing pack size -- would
# report a configuration nobody runs by default.
MESHFOOT_PACK = 1024
# The pack size the performance sweep favours, quoted alongside because the footprint improves
# in the same direction: bigger packs mean proportionally fewer ghosts.
MESHFOOT_PACK_BIG = 4096


def meshfoot_totals(mf, pack=MESHFOOT_PACK):
    """Three totals for the packed mesh's topology, because three different questions get asked.

    *as implemented* is every array the format allocates today. *working set* drops
    ``node_map``, the permutation between packed and unpacked numbering: the apply never reads
    it, and a solver whose fields live in packed numbering throughout does not either. *floor*
    additionally narrows the two reduction-graph offset arrays from 64 to 32 bits, which their
    own lengths permit with three orders of magnitude to spare -- the graph indexes fewer than a
    million entries and spends eight bytes per index doing it.

    All three are reported rather than the flattering one. The gap between the first and the
    third is not a property of the format; it is 64-bit offsets into a small array plus a
    permutation the operator does not read, and the paper says so.
    """
    d = mf.get(pack)
    if not d:
        return None
    a, dofs = d["arrays"], float(d["dofs"])
    impl = a["packed.topology_total"]
    node_map = a.get("packed.node_map", 0)
    # Halving the two offset arrays: ptrdiff_t -> a 32-bit count, which their lengths admit.
    reduce64 = a.get("packed.ghost_reduce_ptr", 0) + a.get("packed.ghost_reduce_idx", 0)
    std = a["standard.topology_total"]
    pts = a["shared.points"]
    working = impl - node_map
    floor = working - reduce64 // 2
    return {
        "pack": pack, "dofs": d["dofs"], "nodes": d["n_nodes"], "n_packs": d["n_packs"],
        "ghost_entries": d["ghost_entries"], "ghost_rows": d["ghost_reduce_rows"],
        "std": std / dofs, "pts": pts / dofs,
        "impl": impl / dofs, "working": working / dofs, "floor": floor / dofs,
        "node_map": node_map / dofs, "reduce_saving": (reduce64 // 2) / dofs,
        "conn": a["packed.elements"] / dofs,
        "r_impl": impl / std, "r_working": working / std, "r_floor": floor / std,
        "r_impl_pts": (impl + pts) / (std + pts),
        # The whole mesh, coordinates included. Reported separately because the coordinates are
        # byte-for-byte identical in both representations, so including them dilutes the ratio
        # without changing any quantity the format controls.
        "std_pts": (std + pts) / dofs, "impl_pts": (impl + pts) / dofs,
    }


def macros_meshfoot(mf):
    """Every footprint figure the prose quotes, at the default pack size and the larger one."""
    t = meshfoot_totals(mf)
    if not t:
        return None
    out = [PREAMBLE]
    for k, fmt in (("std", "%.2f"), ("impl", "%.2f"), ("working", "%.2f"), ("floor", "%.2f"),
                   ("node_map", "%.2f"), ("reduce_saving", "%.2f"), ("conn", "%.2f"),
                   ("std_pts", "%.1f"), ("impl_pts", "%.1f")):
        out.append(r"\newcommand{\fp%s}{%s}" % (k.title().replace("_", ""), fmt % t[k]))
    for k in ("r_impl", "r_working", "r_floor", "r_impl_pts"):
        out.append(r"\newcommand{\fp%sPct}{%.0f}"
                   % (k[2:].title().replace("_", ""), 100.0 * t[k]))
    out.append(r"\newcommand{\fpPack}{%d}" % t["pack"])
    out.append(r"\newcommand{\fpGhostPct}{%.0f}"
               % (100.0 * t["ghost_entries"] / float(t["nodes"])))
    big = meshfoot_totals(mf, MESHFOOT_PACK_BIG)
    if big:
        out.append(r"\newcommand{\fpPackBig}{%d}" % big["pack"])
        out.append(r"\newcommand{\fpFloorBigPct}{%.0f}" % (100.0 * big["r_floor"]))
        out.append(r"\newcommand{\fpImplBigPct}{%.0f}" % (100.0 * big["r_impl"]))
    return "\n".join(out) + "\n"


def table_footprint(rows, mesh=None, n=128):
    """T3. What each representation must read, per degree of freedom, at one size.

    One size rather than four: the per-dof figures move by under two per cent across the range,
    so repeating them four times spent a third of a column to say the same thing.

    ``mesh`` is the measured mesh footprint from meshfoot_totals(), not a model. The packed
    figure it contributes is the format AS IMPLEMENTED, including the two items the text then
    names as avoidable; putting the reduced figure here instead would quote the format at its
    best in the table and its worst in the prose.
    """
    at_n = [r for r in rows if r["_n"] == n and r["operation"] == "bsr_apply"]
    if not at_n:
        return None
    out = [PREAMBLE, r"\small", r"\begin{tabular}{@{}lrr@{}}", r"\toprule",
           r"representation & B/dof & vs.\ packed mesh \\", r"\midrule"]
    base = mesh["impl"] if mesh else None
    if mesh:
        out.append(r"packed mesh & %.1f & --- \\" % mesh["impl"])
        out.append(r"standard mesh & %.1f & $%.2f\times$ \\"
                   % (mesh["std"], mesh["std"] / base))
        out.append(r"\midrule")
    seen = set()
    for store in ("f32", "f64"):
        c = [r for r in at_n if r["bsr_storage"] == store]
        if not c or store in seen:
            continue
        seen.add(store)
        b = c[0]
        blocks, nodes = int(b["bsr_nnz"]), int(b["nodes"])
        vals = float(b["bsr_values_MiB"]) * 1024 * 1024
        idx = blocks * GLOBAL_IDX_BYTES + (nodes + 1) * GLOBAL_IDX_BYTES
        per = (vals + idx) / b["_dofs"]
        rel = (r"$%.0f\times$" % (per / base)) if base else "---"
        out.append(r"assembled matrix, \texttt{%s} & %.0f & %s \\" % (store, per, rel))
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


