# The four convective schemes, and for each the three arms that let one ratio isolate one
# variable: the packed GENERATED kernel, the packed hand-written kernel, and the atomic
# hand-written kernel. generated/hand is a kernel ratio at fixed layout; hand/atomic is a layout
# ratio at fixed kernel. A single "packed" column mixing the two would state neither.
HO_NAME = {
    "first_order": "first-order upwind",
    "ho_unlimited": "deferred correction, unlimited",
    "ho_clip": r"${}+{}$ bounded-face clip",
    "ho_venkatakrishnan": r"${}+{}$ Venkatakrishnan",
    "ho_darwish_moukalled": r"${}+{}$ Darwish--Moukalled",
}

# arm -> (scheme, role). The packed row of each scheme's base arm is the generated kernel; the
# _scalar rows are the hand-written reference. Arms absent here are read but not tabulated:
# ho_unlim_simd is the hand-written vectorised attempt that lost, and the Rhie-Chow pair is
# quoted in the prose rather than given a column, since no other scheme has an RC row to sit
# beside it.
HO_SCALAR_ARM = {
    "ho_unlim_scalar": "ho_unlimited",
    "ho_clip_scalar": "ho_clip",
    "ho_venk_scalar": "ho_venkatakrishnan",
    "ho_dm_scalar": "ho_darwish_moukalled",
}
HO_EXTRA = ("ho_unlim_simd", "ho_unlim_rc", "ho_unlim_rc_scalar")


ConvHo = collections.namedtuple("ConvHo", "arm layout mdof dofs elems flops_elem checksum")


def parse_convho(path):
    """Read jobs/conv_ho_bench.sbatch's summary table.

    Two widths are accepted. The job printed five columns before it carried a work model and
    prints seven now, the two new ones being the element count and the modelled FLOPs per
    element -- which is what puts these arms on the roofline. An archived five-column file
    still parses, with those two fields empty, so a regeneration against older data produces
    the table and simply omits the points that need them.
    """
    known = set(HO_NAME) | set(HO_SCALAR_ARM) | set(HO_EXTRA)
    out = []
    for line in open(path):
        f = line.split()
        if not f or f[0] not in known or len(f) not in (5, 7):
            continue
        if f[1] not in ("atomic", "packed") or f[2] == "-":
            continue
        try:
            if len(f) == 5:
                out.append(ConvHo(f[0], f[1], float(f[2]), int(f[3]), None, None, f[4]))
            else:
                elems = int(f[4]) if f[4] != "-" else None
                fpe = float(f[5]) if f[5] != "-" else None
                out.append(ConvHo(f[0], f[1], float(f[2]), int(f[3]), elems, fpe, f[6]))
        except ValueError:
            continue
    return out


def _convho_index(rows):
    """{scheme: {"gen":x, "hand":x, "atomic":x}} plus the loose arms, by name."""
    by = {}
    loose = {}
    for arm, lay, mdof, _dofs, _e, _fp, _ck in rows:
        if arm in HO_SCALAR_ARM and lay == "packed":
            by.setdefault(HO_SCALAR_ARM[arm], {})["hand"] = mdof
        elif arm in HO_NAME:
            by.setdefault(arm, {})["gen" if lay == "packed" else "atomic"] = mdof
        elif arm in HO_EXTRA and lay == "packed":
            loose[arm] = mdof
    return by, loose


def table_convho(rows):
    """The convective schemes, packed against atomic, at the saturating size.

    Same shape as the completeness ladder: one row per variant, the two layouts side by side, and
    the ratio between them. First-order upwind is a row like the others rather than a separate
    presentation -- it is the scheme the higher-order arms correct, and the question asked of all
    five is the one the paper asks everywhere, which is what the layout is worth.

    Each column is that layout's own shipped kernel, which is the configuration a solver gets.

    The checksum is not printed but is still read: a higher-order row whose checksum equals the
    first-order one did not apply the correction, and its timing is first order measured twice.
    """
    if not rows:
        return None
    by, _loose = _convho_index(rows)
    out = [PREAMBLE, r"\small", r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
           r"convective scheme & packed & atomic & ratio \\",
           r"& \multicolumn{2}{c}{MDOF/s} & \\", r"\midrule"]
    for arm in ("first_order", "ho_unlimited", "ho_clip", "ho_venkatakrishnan",
                "ho_darwish_moukalled"):
        d = by.get(arm)
        if not d:
            continue
        pk, at = d.get("gen"), d.get("atomic")
        ratio = (r"$%.2f\times$" % (pk / at)) if (pk and at) else "---"
        out.append(r"%s & %s & %s & %s \\" % (HO_NAME[arm], _fmt0(pk), _fmt0(at), ratio))
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


def spmv_reference(rows, n=128):
    """The assembled SpMV at one size, for the reference lines on the throughput bar chart.

    Same source as F5, the campaign's bsr_apply rows, and taken at the size the convective arms
    were measured at, so the line and the bars describe the same problem rather than two.
    """
    out = {}
    for store in ("f64", "f32"):
        v = max((r["_mdof"] for r in rows
                 if r["operation"] == "bsr_apply" and r["bsr_storage"] == store
                 and r["_n"] == n), default=None)
        if v:
            out[store] = v
    return out


def fig_convho(rows, spmv=None):
    """The same five variants as a figure, so the trend across schemes reads at a glance.

    A symbolic x axis rather than a size sweep: the higher-order arms are measured at the
    saturating size only, and plotting them against sizes they were not swept over would invent
    data. The two SpMV rates are drawn across it as reference lines, in the colours F5 gives
    them, because what the reader wants from a rate is what it beats.
    """
    if not rows:
        return None
    by, _loose = _convho_index(rows)
    order = [a for a in ("first_order", "ho_unlimited", "ho_clip", "ho_venkatakrishnan",
                         "ho_darwish_moukalled") if a in by]
    if not order:
        return None
    short = {"first_order": "upwind", "ho_unlimited": "unlimited", "ho_clip": "clip",
             "ho_venkatakrishnan": "Venkat.", "ho_darwish_moukalled": "Darwish--M."}
    coords = ",".join(short[a] for a in order)

    def series(key):
        return " ".join("(%s,%.1f)" % (short[a], by[a][key])
                        for a in order if by[a].get(key))

    return PREAMBLE + "\n".join([
        r"\begin{tikzpicture}",
        r"\begin{axis}[width=\columnwidth, height=0.44\columnwidth,",
        r"  ybar, bar width=7pt, ymin=0, ylabel={MDOF/s},",
        # ONE swatch per bar entry. The ybar default draws a pair of bars in the legend, which
        # says nothing here -- each series is one bar per group, not two -- and doubles the width
        # of a legend that also has to hold two dashed reference lines. The SpMV entries below
        # give their own legend image code and are unaffected by this.
        r"  legend image code/.code={\draw[#1] (0cm,-0.09cm) rectangle (0.22cm,0.09cm);},",
        r"  symbolic x coords={%s}, xtick=data," % coords,
        r"  x tick label style={font=\tiny}, enlarge x limits=0.13,",
        r"  legend pos=north east, legend cell align=left,",
        r"  legend style={font=\tiny, draw=none, fill=none, inner sep=1pt},",
        r"  tick label style={font=\scriptsize}, label style={font=\scriptsize},",
        r"  ymajorgrids, major grid style={black!12}]",
        r"\addplot[draw=PackA, fill=PackA] coordinates {%s};" % series("gen"),
        r"\addlegendentry{packed}",
        r"\addplot[draw=PackD, fill=PackD] coordinates {%s};" % series("atomic"),
        r"\addlegendentry{atomic}",
    ] + _convho_spmv_lines(spmv, short[order[0]]) + [
        r"\end{axis}",
        r"\end{tikzpicture}",
    ]) + "\n"


def _convho_spmv_lines(spmv, xref):
    """Horizontal rules at the SpMV rates, with their own legend entries.

    Drawn rather than plotted: the x axis is symbolic, so a rule has to take its x from the axis
    edges and only its y from the data, which is what the -| operator does. The legend image is
    added by hand for the same reason."""
    out = []
    for store, col, lab in (("f64", "PackE", r"BSR SpMV \texttt{f64}"),
                            ("f32", "PackC", r"BSR SpMV \texttt{f32}")):
        v = (spmv or {}).get(store)
        if not v:
            continue
        out.append(r"\draw[%s,dashed,thick] ({axis cs:%s,%.1f} -| {rel axis cs:0,0}) -- "
                   r"({axis cs:%s,%.1f} -| {rel axis cs:1,0});" % (col, xref, v, xref, v))
        # An explicit legend image: the default one for a line-only entry draws a marker box
        # here, which reads as a third kind of thing rather than as the rule it stands for.
        out.append(r"\addlegendimage{legend image code/.code={\draw[%s,dashed,thick] "
                   r"(0cm,0cm) -- (0.45cm,0cm);}}" % col)
        out.append(r"\addlegendentry{%s}" % lab)
    return out


