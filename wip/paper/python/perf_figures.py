def parse_packsize(path):
    """Read jobs/packsize_paper.sbatch: the sweep rows and the ordering rows.

    Returns (sweep, order, meta) where sweep[n] is a list of dicts with the pack size, the pack
    count, packs per thread, mean nodes per pack and both throughputs.
    """
    sweep, order, meta, section = {}, [], {}, None
    for line in open(path):
        s = line.strip()
        if s.startswith("### host"):
            meta["host"] = s.split()[2]
            continue
        if s.startswith("### pack-size sweep"):
            section = "sweep"; continue
        if s.startswith("### spatial ordering"):
            section = "order"; continue
        if s.startswith("#") or not s:
            continue
        f = s.split()
        if section == "sweep" and len(f) == 8 and f[0].isdigit():
            try:
                sweep.setdefault(int(f[0]), []).append({
                    "pack": int(f[1]), "packs": int(f[3]), "ppt": float(f[4]),
                    "mean": int(f[5]), "res": float(f[6]), "jac": float(f[7])})
            except ValueError:
                pass
        elif section == "order" and len(f) == 6 and f[0].isdigit():
            try:
                order.append({"n": int(f[0]), "pack": int(f[1]), "order": f[2],
                              "mean": int(f[3]), "res": float(f[4]), "jac": float(f[5])})
            except ValueError:
                pass
    return sweep, order, meta


