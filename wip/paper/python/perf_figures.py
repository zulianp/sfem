# The ladder, from bare element kernel to the operator a solver actually applies. Each rung adds
# ONE term, and both layouts pay for it, which is the whole reason the ladder is reported: a
# comparison made on the bare kernel overstates the margin a solver receives.
LADDER = [
    (r"element kernel", dict(ran_rc="off", ran_boundary="off", transient="0", pgrad_per_apply="0")),
    (r"${}+{}$ pressure--velocity coupling", dict(ran_rc="on", ran_boundary="off", transient="0", pgrad_per_apply="0")),
    (r"${}+{}$ boundary closure", dict(ran_rc="on", ran_boundary="on", transient="0", pgrad_per_apply="0")),
    (r"${}+{}$ transient term", dict(ran_rc="on", ran_boundary="on", transient="1", pgrad_per_apply="0")),
]


def ladder_ratios(rows, op="residual", n=128):
    """The first and last rungs of the completeness ladder, which the prose quotes."""
    at_n = [r for r in rows if r["_n"] == n and r["operation"] == op]
    got = []
    for _label, sel in LADDER:
        p = best(at_n, ran_layout="packed", **sel)
        a = best(at_n, ran_layout="atomic", **sel)
        if p is not None and a is not None:
            got.append(p / a)
    return (got[0], got[-1]) if got else (None, None)


