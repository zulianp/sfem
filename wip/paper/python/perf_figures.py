def parse_stream(path):
    """Triad rate per thread count, in GB/s.

    STREAM reports MB/s in powers of ten, so the conversion is by 1000 and not 1024; getting
    that wrong overstates the bound by 7% and makes every roofline efficiency look worse.
    """
    rates, threads = {}, None
    for line in open(path):
        t = line.strip()
        if t.startswith("###") and "threads" in t:
            try:
                threads = int(t.split()[1])
            except (IndexError, ValueError):
                threads = None
            continue
        if t.startswith("Triad:") and threads is not None:
            rates[threads] = float(t.split()[1]) / 1000.0
    return rates


def macros_stream(rates):
    """The bound at the measured thread count, and the peak, which are not the same.

    Bandwidth saturates below the full socket, so the 72-thread figure -- the configuration
    every kernel here runs in -- is LOWER than the machine's best. Both are emitted and the
    paper quotes the one matching its configuration, not the flattering one.
    """
    if not rates:
        return PREAMBLE
    full = max(rates)
    best_t = max(rates, key=lambda k: rates[k])
    out = [PREAMBLE]
    out.append(r"\newcommand{\streamTriad}{%.0f}" % rates[full])
    out.append(r"\newcommand{\streamThreads}{%d}" % full)
    out.append(r"\newcommand{\streamPeak}{%.0f}" % rates[best_t])
    out.append(r"\newcommand{\streamPeakThreads}{%d}" % best_t)
    return "\n".join(out) + "\n"


