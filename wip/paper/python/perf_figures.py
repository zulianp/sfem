    if det:
        # The newest run wins; older ones stay on disk as provenance.
        rows, meta = parse_determinism(os.path.join(DATA, det[-1]))
        if rows:
            # No table: the finding is one sentence and the paper says it in prose. The macros
            # stay, because the prose quotes the counts and must not type them.
            with open(os.path.join(out_dir, "determinism_macros.tex"), "w") as fh:
                fh.write(macros_determinism(rows, meta))
            written += ["figures/determinism_macros.tex"]

    camp = [f for f in sorted(os.listdir(DATA)) if f.startswith("campaign_")] if os.path.isdir(DATA) else []
    if camp:
        path = os.path.join(DATA, camp[-1])
        # The mesh half of the footprint table is MEASURED, by the bench's --mesh-footprint
        # mode, which reports each array's own nbytes(). It replaced an arithmetic model that
        # had to guess the ghost and reduction-graph lengths and was about 20% out.
        fr = footprint_rows(path)
        try:
            camp_rows_fp, _h = read_campaign(path)
        except ValueError:
            camp_rows_fp = []
        mfp = [f for f in sorted(os.listdir(DATA)) if f.startswith("meshfoot_")]
        mesh = meshfoot_totals(parse_meshfoot(os.path.join(DATA, mfp[-1]))) if mfp else None
        t_fp = table_footprint(camp_rows_fp, mesh) if camp_rows_fp else None
        if t_fp:
            with open(os.path.join(tab_dir, "footprint.tex"), "w") as fh:
                fh.write(t_fp)
            written.append("tables/footprint.tex")
        if mfp:
            mm = macros_meshfoot(parse_meshfoot(os.path.join(DATA, mfp[-1])))
            if mm:
                with open(os.path.join(out_dir, "meshfoot_macros.tex"), "w") as fh:
                    fh.write(mm)
                written.append("figures/meshfoot_macros.tex")
        try:
            rows, host = read_campaign(path)
        except ValueError as exc:
            print("campaign not usable: %s" % exc)
            rows = []
        if rows:
            # A campaign file is the paper's own only if its name carries the job id that made
            # it, which jobs/camp_full.sbatch now stamps.
            prov = re.match(r"campaign_grace_\d+\.csv$", os.path.basename(path)) is None
            if prov:
                print("  NOTE: %s carries no job id -- figures marked provisional"
                      % os.path.basename(path))
            spmv_ref = spmv_reference(rows)
            with open(os.path.join(out_dir, "throughput_size.tex"), "w") as fh:
                fh.write(fig_throughput(rows, host))
            with open(os.path.join(out_dir, "campaign_macros.tex"), "w") as fh:
                fh.write(macros_throughput(rows, host, provisional=prov))
            written += ["figures/throughput_size.tex", "figures/campaign_macros.tex"]
            lad = table_ladder(rows)
            if lad:
                with open(os.path.join(tab_dir, "ladder.tex"), "w") as fh:
                    fh.write(lad)
                written.append("tables/ladder.tex")

    ts = [f for f in sorted(os.listdir(DATA)) if f.startswith("tscale_")] if os.path.isdir(DATA) else []
    if ts:
        series, meta = parse_scaling(os.path.join(DATA, ts[-1]))
        if series:
            with open(os.path.join(out_dir, "scaling_res.tex"), "w") as fh:
                fh.write(fig_scaling(series, meta, "res"))
            with open(os.path.join(out_dir, "scaling_macros.tex"), "w") as fh:
                fh.write(macros_scaling(series, meta))
            written += ["figures/scaling_res.tex", "figures/scaling_macros.tex"]

    st = [f for f in sorted(os.listdir(DATA)) if f.startswith("stream_")] if os.path.isdir(DATA) else []
    if st:
        rates = parse_stream(os.path.join(DATA, st[-1]))
        if rates:
            with open(os.path.join(out_dir, "stream_macros.tex"), "w") as fh:
                fh.write(macros_stream(rates))
            written.append("figures/stream_macros.tex")

    ps = [f for f in sorted(os.listdir(DATA)) if f.startswith("packsize_")] if os.path.isdir(DATA) else []
    if ps:
        sweep, order, meta = parse_packsize(os.path.join(DATA, ps[-1]))
        if sweep:
            with open(os.path.join(out_dir, "packsize.tex"), "w") as fh:
                fh.write(fig_packsize(sweep, meta))
            with open(os.path.join(out_dir, "packsize_macros.tex"), "w") as fh:
                fh.write(macros_packsize(sweep, order, meta))
            written += ["figures/packsize.tex", "figures/packsize_macros.tex"]
        ordt = table_ordering(order)
        if ordt:
            with open(os.path.join(tab_dir, "ordering.tex"), "w") as fh:
                fh.write(ordt)
            written.append("tables/ordering.tex")

    # Only the .out files: parse_convho reads the whitespace-aligned summary table, not the CSV
    # that sits beside it, and picking the wrong one silently yields an empty table.
    ho = ([f for f in sorted(os.listdir(DATA))
           if f.startswith("convho_") and f.endswith(".out")] if os.path.isdir(DATA) else [])
    if ho:
        hr = parse_convho(os.path.join(DATA, ho[-1]))
        convho_rows = hr
        t = table_convho(hr)
        fg = fig_convho(hr, spmv_ref)
        if fg:
            with open(os.path.join(out_dir, "convho.tex"), "w") as fh:
                fh.write(fg)
            written.append("figures/convho.tex")
        if t:
            with open(os.path.join(tab_dir, "convho.tex"), "w") as fh:
                fh.write(t)
            written.append("tables/convho.tex")
            # A higher-order arm that agrees with first order bit for bit did not run.
            with open(os.path.join(out_dir, "convho_macros.tex"), "w") as fh:
                fh.write(macros_convho(hr))
            written.append("figures/convho_macros.tex")
            for lay in ("atomic", "packed"):
                base = next((r for r in hr if r.arm == "first_order" and r.layout == lay), None)
                if not base:
                    continue
                same = [r.arm for r in hr
                        if r.arm != "first_order" and r.layout == lay
                        and r.checksum == base.checksum]
                if same:
                    print("  WARNING: %s checksum identical to first order -- correction not"
                          " applied in: %s" % (lay, ", ".join(same)))

    ng = [f for f in sorted(os.listdir(DATA)) if f.startswith("ngrad_")] if os.path.isdir(DATA) else []
    if ng:
        nr = parse_ngrad(os.path.join(DATA, ng[-1]))
        if nr:
            with open(os.path.join(out_dir, "ngrad_macros.tex"), "w") as fh:
                fh.write(macros_ngrad(nr))
            written.append("figures/ngrad_macros.tex")

    hx = [f for f in sorted(os.listdir(DATA)) if f.startswith("hoexact_")] if os.path.isdir(DATA) else []
    if hx:
        hr, hc, hf = parse_hoexact(os.path.join(DATA, hx[-1]))
        if hr:
            with open(os.path.join(out_dir, "hoexact_macros.tex"), "w") as fh:
                fh.write(macros_hoexact(hr, hc, hf))
            written.append("figures/hoexact_macros.tex")

    jf = [f for f in sorted(os.listdir(DATA)) if f.startswith("jacfair_")] if os.path.isdir(DATA) else []
    if jf:
        jr = parse_jacfair(os.path.join(DATA, jf[-1]))
        t = table_jacfair(jr)
        if t:
            with open(os.path.join(tab_dir, "jacfair.tex"), "w") as fh:
                fh.write(t)
            with open(os.path.join(out_dir, "jacfair_macros.tex"), "w") as fh:
                fh.write(macros_jacfair(jr))
            written += ["tables/jacfair.tex", "figures/jacfair_macros.tex"]

    # F8 needs three things from three different jobs: the campaign (points), STREAM (memory
    # roof) and the GEMM peak (compute roof). Emitted only when all three are present, so a
    # roofline is never drawn with a roof that was assumed.
    pk = [f for f in sorted(os.listdir(DATA)) if f.startswith("peak_")] if os.path.isdir(DATA) else []
    if camp and st and pk and rows:
        peak = parse_peak(os.path.join(DATA, pk[-1]))
        rates = parse_stream(os.path.join(DATA, st[-1]))
        bw = rates.get(max(rates)) if rates else None
        # Measured DRAM traffic per dof, if a differenced SCF capture is present. Preferred over
        # the model; see roofline_points.
        # EVERY dram_ file, not the newest: the captures were made by different jobs for
        # different operators, each file named for the jobs behind it, and taking one would
        # silently drop whichever operator was measured first.
        dm = [f for f in sorted(os.listdir(DATA)) if f.startswith("dram_")]
        measured_dram = {}
        for name in dm:
            measured_dram.update(parse_dram(os.path.join(DATA, name)))
        if peak and bw:
            pts = roofline_points(rows, n=128, measured_bytes=measured_dram)
            ho_path = roofline_ho_points(convho_rows, measured_dram)
            if pts:
                with open(os.path.join(out_dir, "roofline.tex"), "w") as fh:
                    fh.write(fig_roofline(pts, bw, peak, ho=ho_path))
                with open(os.path.join(out_dir, "roofline_macros.tex"), "w") as fh:
                    fh.write(PREAMBLE
                             + "\\newcommand{\\rlPeak}{%.0f}\n" % peak
                             + "\\newcommand{\\rlBw}{%.0f}\n" % bw
                             + "\\newcommand{\\rlRidge}{%.1f}\n" % (peak / bw)
                             + macros_roofline_ho(ho_path, measured_dram)
                             + "\\newcommand{\\rlSpecPeak}{%.2f}\n" % (SPEC_PEAK_GFLOPS / 1000.0)
                             + "\\newcommand{\\rlSpecBw}{%.0f}\n" % SPEC_BW_GBS
                             + "\\newcommand{\\rlSpecRidge}{%.1f}\n"
                               % (SPEC_PEAK_GFLOPS / SPEC_BW_GBS)
                             + "\\newcommand{\\rlPeakPctSpec}{%.0f}\n"
                               % (100.0 * peak / SPEC_PEAK_GFLOPS)
                             + "\\newcommand{\\rlBwPctSpec}{%.0f}\n"
                               % (100.0 * bw / SPEC_BW_GBS)
                             + "".join("\\newcommand{\\rl%s}{%.0f}\n" % (_macro_name(l), g)
                                       for l, a, g, _m in pts)
                             + "".join("\\newcommand{\\rl%sAi}{%.1f}\n" % (_macro_name(l), a)
                                       for l, a, g, _m in pts)
                             # Each point as a percentage of the roof BINDING AT ITS OWN
                             # intensity -- memory below the ridge, compute above. This is the
                             # comparison the figure invites and it is easy to state wrongly by
                             # dividing everything by the compute peak.
                             + "".join("\\newcommand{\\rl%sPct}{%.0f}\n"
                                       % (_macro_name(l), 100.0 * g / min(peak, bw * a))
                                       for l, a, g, _m in pts)
                             + "\\newcommand{\\rlTrafficSource}{%s}\n"
                               % ("measured" if any(m for _l, _a, _g, m in pts) else "modelled"))
                written += ["figures/roofline.tex", "figures/roofline_macros.tex"]
    return written


