def parse_determinism(path):
    """Read jobs/det_layout.sbatch's output.

    The job prints one row per (layout, operation) as "<d> distinct / <n> runs" for two
    questions: repeats at a fixed thread count, and one run at each of several thread counts.
    Returns [(layout, op, (d_a, n_a), (d_b, n_b))] plus the header facts, so the caption can
    state the problem size and the thread counts rather than have them typed in.
    """
    rows, meta = [], {}
    for line in open(path):
        s = line.strip()
        if s.startswith("### host"):
            # "### host nid006545  n=100  repeats=3 at 72t  thread sweep: 1 8 36 72"
            parts = s.split()
            meta["host"] = parts[2]
            for tok in parts:
                if tok.startswith("n="):
                    meta["n"] = tok[2:]
                if tok.startswith("repeats="):
                    meta["repeats"] = tok[len("repeats="):]
            if "thread sweep:" in s:
                meta["threads"] = s.split("thread sweep:")[1].strip()
            continue
        # layout op <d> distinct / <n> runs   <d> distinct / <n> runs
        #
        # Matched rather than split on whitespace: the job appends "(INCOMPLETE)" to a cell
        # whose runs did not all produce a fingerprint, which shifts every later field and
        # silently mis-parsed the row when this counted tokens.
        m = _DET_ROW.match(s)
        if m:
            rows.append((m.group(1), m.group(2),
                         (int(m.group(3)), int(m.group(4))),
                         (int(m.group(5)), int(m.group(6)))))
    return rows, meta


OP_NAME = {"res": "residual", "jac": "Jacobian action"}


def table_determinism(rows, meta):
    """T2. The verdict column is the point: 1 distinct output means bit-reproducible.

    Rows are compared DOWN a column and never across, because packing renumbers the mesh and a
    fingerprint folds the output in node order -- so two layouts disagree by construction even
    when both are perfectly reproducible. The table says so in its own note rather than relying
    on the prose to carry it.
    """
    out = [PREAMBLE, r"\begin{tabular}{llcc}", r"\toprule",
           r"& & \multicolumn{2}{c}{distinct outputs} \\",
           r"\cmidrule(lr){3-4}",
           r"layout & operator & repeats & thread counts \\",
           r"\midrule"]
    for layout, op, a, b in rows:
        verdict = lambda d, n: (r"\textbf{%d} / %d" % (d, n)) if d == 1 else ("%d / %d" % (d, n))
        out.append(r"\texttt{%s} & %s & %s & %s \\"
                   % (layout, OP_NAME.get(op, op), verdict(*a), verdict(*b)))
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


def macros_determinism(rows, meta):
    """The facts the caption and prose quote, so no digit is typed twice."""
    out = [PREAMBLE]
    out.append(r"\newcommand{\detHost}{%s}" % meta.get("host", "?"))
    out.append(r"\newcommand{\detN}{%s}" % meta.get("n", "?"))
    out.append(r"\newcommand{\detRepeats}{%s}" % meta.get("repeats", "?"))
    out.append(r"\newcommand{\detThreads}{%s}" % meta.get("threads", "?").replace(" ", ", "))
    for layout, op, a, b in rows:
        key = (layout + op).capitalize()
        out.append(r"\newcommand{\det%sRep}{%d}" % (key, a[0]))
        out.append(r"\newcommand{\det%sThr}{%d}" % (key, b[0]))
    return "\n".join(out) + "\n"


