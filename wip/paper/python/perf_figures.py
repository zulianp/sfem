LAYOUT_STYLE = {
    "packed":  ("PackA", "*"),
    "atomic":  ("PackD", "square*"),
    "colored": ("PackC", "triangle*"),
}


def parse_scaling(path):
    """Read jobs/thread_scaling.sbatch's table.

    Returns {(layout, op): [(threads, mdof)]} plus meta. Rows whose throughput is a dash are
    dropped rather than read as zero: a missing measurement must not become a point at the
    origin, which would bend a scaling curve toward superlinearity.
    """
    series, meta = {}, {}
    for line in open(path):
        t = line.strip()
        if t.startswith("### host"):
            parts = t.split()
            meta["host"] = parts[2]
            for tok in parts:
                if tok.startswith("n="):
                    meta["n"] = tok[2:]
            continue
        f = t.split()
        if len(f) >= 4 and f[0] in LAYOUT_STYLE and f[1] in ("res", "jac"):
            if f[3] == "-":
                continue
            try:
                thr, mdof = int(f[2]), float(f[3])
            except ValueError:
                continue
            series.setdefault((f[0], f[1]), []).append((thr, mdof))
            if len(f) > 4 and f[4] != "-":
                meta["packs"] = f[4]
    for k in series:
        series[k].sort()
    return series, meta


def fig_scaling(series, meta, op="res"):
    """F6. Throughput against thread count, log-log with an ideal line.

    Log-log because the content is the DEPARTURE from ideal, and on linear axes the low thread
    counts are invisible.
    """
    out = [PREAMBLE,
           r"\begin{tikzpicture}",
           r"\begin{loglogaxis}[",
           r"  width=\columnwidth, height=0.55\columnwidth,",
           r"  xlabel={OpenMP threads}, ylabel={MDOF/s},",
           r"  log basis x=2, xtick={1,2,4,8,18,36,72}, xticklabels={1,2,4,8,18,36,72},",
           r"  legend pos=north west, legend cell align=left,",
           r"  legend style={font=\tiny, draw=none, fill=none, inner sep=1pt},",
           r"  grid=both, major grid style={black!12}, minor grid style={black!6},",
           r"  tick label style={font=\tiny}, label style={font=\scriptsize},",
           r"]"]
    # The ideal line is anchored on the SLOWEST layout at one thread, so the reference is not
    # drawn from the layout being advocated.
    base = None
    for layout in ("atomic", "packed", "colored"):
        pts = series.get((layout, op))
        if pts and pts[0][0] == 1 and (base is None or pts[0][1] < base[1]):
            base = pts[0]
    if base:
        t0, m0 = base
        out.append(r"\addplot[black!45,dashed,no marks,forget plot] coordinates "
                   r"{(1,%.4f) (72,%.4f)};" % (m0, m0 * 72.0 / t0))
        out.append(r"\node[black!55,font=\tiny,rotate=37,anchor=south east] "
                   r"at (axis cs:36,%.1f) {ideal};" % (m0 * 30.0))
    for layout in ("packed", "atomic", "colored"):
        pts = series.get((layout, op))
        if not pts:
            continue
        col, mark = LAYOUT_STYLE[layout]
        out.append(r"\addplot[%s,mark=%s,mark size=1.4pt,thick] coordinates {%s};"
                   % (col, mark, " ".join("(%d,%.4f)" % q for q in pts)))
        out.append(r"\addlegendentry{\texttt{%s}}" % layout)
    out.append(r"\end{loglogaxis}")
    out.append(r"\end{tikzpicture}")
    return "\n".join(out) + "\n"


def macros_scaling(series, meta):
    """Endpoints, speedups and efficiencies, so the prose quotes no typed digit."""
    out = [PREAMBLE]
    out.append(r"\newcommand{\scaleHost}{%s}" % meta.get("host", "?"))
    out.append(r"\newcommand{\scalePacks}{%s}" % meta.get("packs", "?"))
    names = {"res": "Res", "jac": "Jac"}
