def _macro_name(label):
    """A LaTeX-safe, UNIQUE macro suffix for a roofline label.

    LaTeX command names may not contain digits, so the obvious "strip non-alpha" rule maps
    "SpMV f64" and "SpMV f32" onto the same name and emits \\newcommand twice for it, which is
    an error. Digits are spelled out instead, which keeps the names distinct and readable.
    """
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
              "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    out = []
    for c in label.replace("\\texttt", " ").title():
        if c.isalpha():
            out.append(c)
        elif c in digits:
            out.append(digits[c])
    return "".join(out)


