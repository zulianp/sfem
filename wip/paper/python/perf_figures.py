def selftest():
    fails = []

    def check(ok, what, detail=""):
        print("%-62s %s%s" % (what, "OK" if ok else "FAIL", ("  " + detail) if detail and not ok else ""))
        if not ok:
            fails.append(what)

    import tempfile

    sample = (
        "### host nid000000  n=100  repeats=3 at 72t  thread sweep: 1 8 36 72\n"
        "### fingerprints are comparable only DOWN a column\n"
        "\n"
        "layout    op    A: repeats @72t              B: across threads\n"
        "atomic    res   3 distinct / 3 runs          4 distinct / 4 runs\n"
        "packed    res   1 distinct / 3 runs          1 distinct / 4 runs\n"
        "colored   jac   1 distinct / 3 runs          2 distinct / 4 runs\n"
    )
    with tempfile.TemporaryDirectory() as td:
        p = os.path.join(td, "det_layout_1.out")
        open(p, "w").write(sample)
        rows, meta = parse_determinism(p)

        check(len(rows) == 3, "every data row is parsed, header lines are not", "got %d" % len(rows))
        check(meta.get("host") == "nid000000" and meta.get("n") == "100",
              "the header's host and problem size are recovered")
        check(meta.get("threads") == "1 8 36 72", "the thread sweep is recovered")
        check(rows[0] == ("atomic", "res", (3, 3), (4, 4)), "an irreproducible row parses",
              str(rows[0]))
        check(rows[1] == ("packed", "res", (1, 3), (1, 4)), "a reproducible row parses",
              str(rows[1]))

        # No table any more: the finding is one sentence of prose, so what has to hold is that
        # the macros the prose quotes carry the verdict -- one distinct output where the layout
        # is reproducible, more where it is not.
        mac = macros_determinism(rows, meta)
        check(r"\newcommand{\detPackedresRep}{1}" in mac and r"\newcommand{\detAtomicresThr}{4}" in mac,
              "the macros carry the verdict the prose quotes")
        check(r"\newcommand{\detHost}{nid000000}" in mac, "the host macro is emitted")
        check(r"\newcommand{\detAtomicresRep}{3}" in mac, "a per-row macro is emitted")
        # LaTeX command names cannot contain digits or underscores.
        bad = [m for m in re.findall(r"\\newcommand\{\\([A-Za-z0-9]*)\}", mac)
               if not m.isalpha()]
        check(not bad, "every emitted macro name is alphabetic", str(bad))

        # STREAM: the unit conversion and the "peak is not at full socket" case.
        sp = os.path.join(td, "stream_1.out")
        open(sp, "w").write("### host nidX\n### 72 threads\n  Triad:   450596.7  0.1 0.1 0.1\n"
                            "### 36 threads\n  Triad:   480349.8  0.1 0.1 0.1\n")
        rates = parse_stream(sp)
        check(rates == {72: 450.5967, 36: 480.3498}, "stream triad parses in GB/s", str(rates))
        sm = macros_stream(rates)
        check(r"\newcommand{\streamTriad}{451}" in sm,
              "the bound quoted is the one at the measured thread count")
        check(r"\newcommand{\streamPeak}{480}" in sm and
              r"\newcommand{\streamPeakThreads}{36}" in sm,
              "the peak is reported separately, with the count it occurred at")

        # Campaign: the multi-host refusal, the bare-kernel predicate and the ladder.
        cp = os.path.join(td, "campaign_x.csv")
        hdr = ("host,operation,layout,ran_layout,kernel,cube_n,nodes,elements,dofs,bsr_nnz,"
               "bsr_values_MiB,bsr_storage,MDOF_s,ran_rc,ran_boundary,transient,pgrad_per_apply")
        def row(host, op, lay, n, mdof, rc="off", bnd="off", tr="0", pg="0", store="n/a"):
            return ",".join([host, op, lay, lay, "sumfact", str(n), "10", "8", "40", "0",
                             "0", store, str(mdof), rc, bnd, tr, pg])
        open(cp, "w").write("\n".join([hdr,
            row("nidA", "residual", "packed", 128, 2600),
            row("nidA", "residual", "atomic", 128, 850),
            row("nidA", "residual", "packed", 128, 1300, rc="on"),
            row("nidA", "residual", "atomic", 128, 600, rc="on"),
            row("nidA", "bsr_apply", "packed", 128, 450, store="f64"),
        ]) + "\n")
        rws, hst = read_campaign(cp)
        check(hst == "nidA" and len(rws) == 5, "a single-host campaign reads")
        check(sum(1 for r in rws if _bare(r)) == 3, "the bare-kernel predicate selects only bare rows",
              str(sum(1 for r in rws if _bare(r))))
        lad = table_ladder(rws)
        check(lad is not None and r"3.06\times" in lad.replace("\\times", "\\times"),
              "the ladder reports the bare rung ratio")
        check(r"1300" in lad and r"600" in lad, "the ladder reports the coupled rung")
        mac = macros_throughput(rws, hst)
        check(r"\newcommand{\campHost}{nidA}" in mac, "the campaign host is emitted for provenance")
        check(r"\newcommand{\campResPacked}{2600}" in mac, "the bare packed headline is emitted")
        check(r"\newcommand{\campProvisional}{0}" in mac,
              "a campaign is not marked provisional unless asked")
        check(r"\newcommand{\campProvisional}{1}" in macros_throughput(rws, hst, provisional=True),
              "the provisional marker is emitted when the data carries no job id")

        open(cp, "a").write(row("nidB", "residual", "packed", 128, 9999) + "\n")
        try:
            read_campaign(cp)
            check(False, "a multi-host campaign is refused")
        except ValueError:
            check(True, "a multi-host campaign is refused")

        # ---- the measured mesh footprint --------------------------------------------------
        # The arithmetic here is small but every number in it reaches the paper, and the three
        # totals differ only by which arrays they include -- exactly the kind of accounting
        # that is easy to get subtly wrong and impossible to notice afterwards.
        mf_sample = (
            "### mesh footprint, some host\n"
            "@@@ pack_size 1024\n"
            "### mesh footprint  n_nodes=1000 n_elements=900 dofs=4000\n"
            "### n_packs=4 elements_per_pack=1024 packed_elements=900 "
            "ghost_entries=200 ghost_reduce_rows=150\n"
            "\n"
            "array                                 bytes        B/dof\n"
            "standard.topology_total                40000        10.000\n"
            "packed.elements                        20000         5.000\n"
            "packed.ghost_reduce_ptr                 4000         1.000\n"
            "packed.ghost_reduce_idx                 4000         1.000\n"
            "packed.node_map                         4000         1.000\n"
            "packed.topology_total                  32000         8.000\n"
            "shared.points                          12000         3.000\n"
            "\npacked/standard topology_only   0.8000\n"
        )
        with tempfile.TemporaryDirectory() as td3:
            mp = os.path.join(td3, "meshfoot_x.out")
            open(mp, "w").write(mf_sample)
            mf = parse_meshfoot(mp)
            check(list(mf) == [1024], "one pack-size block is parsed", "got %s" % list(mf))
            check(mf[1024]["ghost_entries"] == 200 and mf[1024]["ghost_reduce_rows"] == 150,
                  "the ghost and reduction-graph counts are read, not derived")
            t = meshfoot_totals(mf)
            check(abs(t["impl"] - 8.0) < 1e-9, "the implemented total is the reported one")
            check(abs(t["working"] - 7.0) < 1e-9,
                  "the working set drops node_map and nothing else")
            check(abs(t["floor"] - 6.0) < 1e-9,
                  "the floor halves both reduction offset arrays and nothing else")
            check(t["floor"] < t["working"] < t["impl"],
                  "the three totals are ordered, so none can silently be the flattering one")
            check(abs(t["std_pts"] - 13.0) < 1e-9 and abs(t["impl_pts"] - 11.0) < 1e-9,
                  "the coordinates are added to both representations, never to one")
            check(abs(t["r_impl"] - 0.8) < 1e-9,
                  "the implemented ratio matches what the bench itself printed")
            # A missing block must yield nothing rather than a partial total.
            check(meshfoot_totals(mf, 99999) is None,
                  "a pack size that was not measured yields no total")

        # ---- measured DRAM traffic --------------------------------------------------------
        # The differencing is the whole point of the two-capture format, and getting it wrong
        # would silently divide setup and warmup into the per-apply figure.
        with tempfile.TemporaryDirectory() as td4:
            dp = os.path.join(td4, "dram_x.out")
            open(dp, "w").write(
                "# comment\n"
                "residual  packed  10  40   1000   4000   100\n"
                "residual  atomic  10  40   2000   2300   100\n")
            dm = parse_dram(dp)
            # (4000-1000)/(40-10)/100 = 1.0 byte per dof per apply
            check(abs(dm[("residual", "packed")] - 1.0) < 1e-12,
                  "traffic is differenced across repeat count, not divided by it")
            check(abs(dm[("residual", "atomic")] - 0.1) < 1e-12,
                  "a second configuration is read independently")
            check(("residual", "colored") not in dm,
                  "a configuration absent from the capture yields no entry")

        # A point with measured traffic must report it as measured, and one without must not.
        camp_pts = [{"_n": 128, "_dofs": 400, "_mdof": 100.0, "operation": "residual",
                     "ran_layout": "packed", "GFLOP_s_model": "40", "elements": "100",
                     "nodes": "100", "ran_rc": "off", "ran_boundary": "off", "transient": "0"}]
        got = roofline_points(camp_pts, n=128, measured_bytes={("residual", "packed"): 2.0})
        check(bool(got) and got[0][3] is True and abs(got[0][1] - 200.0) < 1e-9,
              "measured traffic is used where present, and flagged")
        got = roofline_points(camp_pts, n=128, measured_bytes={})
        check(bool(got) and got[0][3] is False,
              "the model is used where no measurement exists, and flagged")

        # Missing data must be absent, not fabricated.
        with tempfile.TemporaryDirectory() as td2:
            written = build(os.path.join(td2, "f"), os.path.join(td2, "t"))
            check(isinstance(written, list), "build returns the list of files it wrote")

    print()
    if fails:
        print("%d check(s) FAILED" % len(fails))
        return 1
    print("all performance-figure checks passed")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(HERE, "..", "figures"))
    ap.add_argument("--tables", default=os.path.join(HERE, "..", "tables"))
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()

    if args.selftest:
        sys.exit(selftest())

    written = build(args.out, args.tables)
    if not written:
        print("no measurements in %s yet -- see README.md for the programme" % os.path.abspath(DATA))
    for w in written:
        print("wrote %s" % w)


if __name__ == "__main__":
    main()
