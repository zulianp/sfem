# One row of the determinism table. Anchored on the two "<d> distinct / <n> runs" cells so
# that an appended marker such as "(INCOMPLETE)" cannot shift the fields.
_DET_ROW = re.compile(
    r"^(atomic|packed|colored|store)\s+(\w+)\s+"
    r"(\d+)\s+distinct\s*/\s*(\d+)\s+runs\S*\s+"
    r"(\d+)\s+distinct\s*/\s*(\d+)\s+runs")

