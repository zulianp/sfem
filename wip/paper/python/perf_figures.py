def parse_determinism(path):
    """Read jobs/det_layout.sbatch's output.

    The job prints one row per (layout, operation) as "<d> distinct / <n> runs" for two
    questions: repeats at a fixed thread count, and one run at each of several thread counts.
    Returns [(layout, op, (d_a, n_a), (d_b, n_b))] plus the header facts, so the caption can
    state the problem size and the thread counts rather than have them typed in.
    """
    rows, meta = [], {}
    for line in open(path):
        s = line.strip()
        if s.startswith("### host"):
            # "### host nid006545  n=100  repeats=3 at 72t  thread sweep: 1 8 36 72"
            parts = s.split()
            meta["host"] = parts[2]
            for tok in parts:
                if tok.startswith("n="):
                    meta["n"] = tok[2:]
                if tok.startswith("repeats="):
                    meta["repeats"] = tok[len("repeats="):]
            if "thread sweep:" in s:
                meta["threads"] = s.split("thread sweep:")[1].strip()
            continue
        # layout op <d> distinct / <n> runs   <d> distinct / <n> runs
        #
        # Matched rather than split on whitespace: the job appends "(INCOMPLETE)" to a cell
        # whose runs did not all produce a fingerprint, which shifts every later field and
        # silently mis-parsed the row when this counted tokens.
        m = _DET_ROW.match(s)
        if m:
            rows.append((m.group(1), m.group(2),
                         (int(m.group(3)), int(m.group(4))),
                         (int(m.group(5)), int(m.group(6)))))
    return rows, meta


