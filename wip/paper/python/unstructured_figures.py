"""Generate the irregular-mesh comparison from the checked Grace archive."""
import hashlib
import importlib.util
import json
from pathlib import Path
import statistics
import tarfile

ROOT = Path(__file__).resolve().parents[3]
PARSER = ROOT / 'spikes/cvfem/scripts/unstructured_study.py'
spec = importlib.util.spec_from_file_location('unstructured_study', str(PARSER))
study = importlib.util.module_from_spec(spec)
spec.loader.exec_module(study)
RUNS = {'first_order': ('5306375', 'nid005717'), 'darwish': ('5305511', 'nid005379')}
PREAMBLE = '% Generated by python/unstructured_figures.py; do not edit.\n'


def require(ok, message):
    if not ok:
        raise ValueError(message)


def read_study(directory):
    directory = Path(directory)
    kit = directory/'kit'
    manifest = {}
    for line in (kit/'SHA256SUMS').read_text().splitlines():
        digest, name = line.split('  ', 1)
        require(name not in manifest and not Path(name).is_absolute() and
                '..' not in Path(name).parts, 'invalid kit manifest')
        manifest[name] = digest
        require(hashlib.sha256((kit/name).read_bytes()).hexdigest() == digest,
                'changed kit file: '+name)
    require(len(manifest) == 48, 'incomplete kit manifest')
    source = json.loads((kit/'SOURCE.json').read_text())
    require(hashlib.sha256((kit/'source.tar').read_bytes()).hexdigest() == source['source_sha256'],
            'changed source archive')
    require(source['files'][str(PARSER.relative_to(ROOT))] ==
            hashlib.sha256(PARSER.read_bytes()).hexdigest(), 'measurement parser changed')
    with tarfile.open(kit/'source.tar') as tar:
        members = tar.getmembers()
        require(len(members) == len(source['files']) and
                {m.name for m in members} == set(source['files']), 'incomplete source snapshot')
        for member in members:
            require(member.isfile() and hashlib.sha256(tar.extractfile(member).read()).hexdigest()
                    == source['files'][member.name], 'changed source file')
    identities = {mesh: study.mesh_identity(kit/'meshes'/('mesh-'+mesh))
                  for mesh in ('small','medium','large')}
    expected = {(m,t,p,False) for m in ('medium','large') for t in (1,72) for p in (256,1024)}
    expected |= {('small',t,p,True) for t in (1,72) for p in (64,256)}
    result = []
    for scheme, (job, host) in RUNS.items():
        run = directory/'runs'/job
        log = (run/'run.log').read_text()
        lines = log.splitlines()
        require(lines[0].startswith('RESULTS=') and scheme+'-'+job+'-' in lines[0]
                and lines[2] == host, 'run identity differs')
        remote = lines[0].split('=',1)[1]
        require('100% tests passed, 0 tests failed out of 10' in log and
                'BASELINE COMPARISON t1: pass' in log and 'BASELINE COMPARISON t72: pass' in log
                and scheme+' IRREGULAR CHECKS AND TIMINGS COLLECTED: '+remote in log,
                'incomplete native checks or campaign')
        require(json.loads((run/'baseline-comparison/status.json').read_text()) ==
                {'existing_failure': False}, 'baseline comparison failed')
        require(set((run/'kit-verification.txt').read_text().splitlines()) ==
                {name+': OK' for name in manifest}, 'kit verification differs')
        require(len(json.loads((run/'binding.json').read_text())['cpus']) == 72,
                'wrong CPU allocation')
        binaries = dict(line.split('  ',1)[::-1] for line in (run/'binaries.sha256').read_text().splitlines())
        records = json.loads((run/'study/records.json').read_text())
        require(len(records) == len(expected) and
                {(r['mesh'],r['threads'],r['pack'],r['verify']) for r in records} == expected,
                'incomplete or duplicate cases')
        for row in records:
            require(row['scheme'] == scheme and row['memory_policy'] == 'THP disabled',
                    'wrong scheme or memory policy')
            require(row['identity'] == identities[row['mesh']], 'mesh identity differs')
            require(row['binary_sha256'] == binaries[remote+'/build/irregular'], 'binary differs')
            name = '{}-{}-t{}-p{}-{}'.format(scheme,row['mesh'],row['threads'],row['pack'],
                                             'check' if row['verify'] else 'timing')
            case = run/'study'/name
            command = json.loads((case/'command.json').read_text())
            require(command == {k:v for k,v in row.items() if k != 'result'}, 'command record differs')
            expected_command = ['/user-environment/env/default/bin/python3',
                remote+'/source/spikes/cvfem/scripts/roofline_thp_exec.py','disabled','--',
                remote+'/build/irregular','--scheme',scheme,'--mesh',
                remote+'/kit/meshes/mesh-'+row['mesh'],'--pack-size',str(row['pack'])]
            expected_command += ['--verify-only'] if row['verify'] else [
                '--blocks','12','--repeat','12','--warmup','10']
            require(row['command'] == expected_command, 'measurement arguments differ')
            text = (case/'run.log').read_text()
            require('THP_LAUNCH policy=disabled disabled=1 ' in text, 'missing policy readback')
            require(study.check(text,row['identity'],row['threads'],row['pack'],12,12,
                                row['verify'],scheme) == row['result'], 'raw capture differs')
        require(study.summary(records) == (run/'study/summary.md').read_text(),
                'saved summary differs from raw captures')
        result.extend(records)
    return result


def ratios(row, operator):
    samples = {(int(s['block']), s['layout']): float(s['seconds'])
               for s in row['result']['samples'] if s['op'] == operator}
    atomic = [samples[b, 'atomic'] for b in range(12)]
    packed = [samples[b, 'packed'] for b in range(12)]
    paired = [a / p for a, p in zip(atomic, packed)]
    return statistics.mean(atomic) / statistics.mean(packed), min(paired), max(paired)


def outputs(records):
    rows = {(r['scheme'],r['mesh'],r['pack']):r for r in records
            if not r['verify'] and r['threads'] == 72}
    table = [PREAMBLE, r'\begin{tabular}{@{}lrrr@{}}', r'\toprule',
             r'Mesh & Pack & Residual ratio [range] & $Jv$ ratio [range] \\', r'\midrule']
    for scheme, title in (('first_order','First-order upwind'),('darwish','Darwish')):
        table.append(r'\multicolumn{4}{l}{\emph{'+title+r'}} \\')
        for mesh,label in (('medium','M'),('large','L')):
            for pack in (256,1024):
                cells = [label,str(pack)]
                for op in ('residual','jacobian'):
                    cells.append('{:.3f} [{:.3f}, {:.3f}]'.format(*ratios(rows[scheme,mesh,pack],op)))
                table.append(' & '.join(cells)+r' \\')
        if scheme == 'first_order':
            table.append(r'\midrule')
    values = dict(Threads=72, Blocks=12, Repeat=12, Warmup=10)
    for mesh,label in (('medium','Medium'),('large','Large')):
        values[label+'Cells'] = rows['first_order',mesh,256]['identity']['elements']
    for scheme,label in (('first_order','First'),('darwish','Darwish')):
        row = rows[scheme,'medium',1024]
        values[label+'MediumBigSlowdown'] = '{:.1f}'.format(100*(1/ratios(row,'jacobian')[0]-1))
    values['MediumBigPacks'] = (values['MediumCells']+1023)//1024
    macros = PREAMBLE+''.join(r'\newcommand{\unstr%s}{%s}'%(k,v)+'\n' for k,v in values.items())
    return '\n'.join(table+[r'\bottomrule',r'\end{tabular}','']),macros


def build(data, figures, tables):
    table, macros = outputs(read_study(data))
    files = [(Path(tables) / 'unstructured.tex', table),
             (Path(figures) / 'unstructured_macros.tex', macros)]
    for path, text in files:
        path.write_text(text)
    return [str(p) for p, _ in files]


def selftest(data):
    rows = read_study(data)
    table, macros = outputs(rows)
    assert '0.888 [0.881, 0.900]' in table and '0.848 [0.795, 0.891]' in table
    assert '1.019 [0.936, 1.034]' in table
    assert 'FirstMediumBigSlowdown}{12.6}' in macros and 'DarwishMediumBigSlowdown}{17.9}' in macros
    # Every run must be complete; a successful table cannot hide a failing case.
    run = Path(data)/'runs/5306375'
    record = run/'study/records.json'
    content = json.loads(record.read_text())
    trials = [(record,json.dumps(content[:-1])),
              (record,json.dumps(content[:-1]+[content[0]])),
              (run/'baseline-comparison/status.json','{"existing_failure": true}'),
              (run/'run.log',(run/'run.log').read_text().replace('10\n','9\n'))]
    darwish = Path(data)/'runs/5305511/study/darwish-medium-t72-p256-timing/run.log'
    trials.append((darwish,darwish.read_text().replace('crossings=0','crossings=1')))
    trials.append((record,record.read_text().replace('"first_order"','"darwish"')))
    for file,changed in trials:
        original = file.read_bytes()
        require(changed.encode() != original, 'ineffective refusal control')
        try:
            file.write_text(changed)
            try:
                read_study(data)
            except (ValueError,KeyError):
                pass
            else:
                raise AssertionError('changed or missing evidence accepted')
        finally:
            file.write_bytes(original)
    return True

