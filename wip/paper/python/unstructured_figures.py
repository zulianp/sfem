"""Generate the irregular-mesh comparison from the checked Grace archive."""
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import statistics
import tempfile

ROOT = Path(__file__).resolve().parents[3]
PARSER = ROOT / 'spikes/cvfem/scripts/unstructured_study.py'
spec = importlib.util.spec_from_file_location('unstructured_study', str(PARSER))
study = importlib.util.module_from_spec(spec)
spec.loader.exec_module(study)
DATASET = 'unstructured_5052301'
PREAMBLE = '% Generated by python/unstructured_figures.py; do not edit.\n'


def require(ok, message):
    if not ok:
        raise ValueError(message)


def read_study(directory):
    directory = Path(directory)
    hashes = {}
    for line in (directory / 'RAW-SHA256.txt').read_text().splitlines():
        digest, name = line.split('  ', 1)
        require(name not in hashes and name.startswith('raw/') and
                '..' not in Path(name).parts, 'invalid archive manifest')
        hashes[name] = digest
        require(hashlib.sha256((directory / name).read_bytes()).hexdigest() == digest,
                'unstructured evidence hash mismatch: ' + name)
    require(len(hashes) == 50 and set(hashes) == {
        str(p.relative_to(directory)) for p in (directory / 'raw').rglob('*') if p.is_file()
    }, 'incomplete unstructured archive')
    sources = dict(line.split('  ', 1)[::-1] for line in
                   (directory / 'raw/SOURCE-SHA256.txt').read_text().splitlines())
    require(sources['sfem/spikes/cvfem/scripts/unstructured_study.py'] ==
            hashlib.sha256(PARSER.read_bytes()).hexdigest(), 'measurement parser changed')
    run = (directory / 'raw/run.log').read_text()
    require(run.splitlines()[1] == 'nid006545' and
            'unstructured-5052301-wDO4No' in run, 'unstructured run identity differs')
    binaries = dict(line.split('  ', 1)[::-1] for line in
                    (directory / 'raw/BUILD-SHA256.txt').read_text().splitlines())
    records = json.loads((directory / 'raw/study/records.json').read_text())
    expected = {(m, t, p, False) for m in ('medium', 'large')
                for t in (1, 72) for p in (256, 1024)}
    expected |= {('small', t, p, True) for t in (1, 72) for p in (64, 256)}
    require(len(records) == len(expected) and {
        (r['mesh'], r['threads'], r['pack'], r['verify']) for r in records
    } == expected, 'incomplete or duplicate unstructured cases')
    identities = {}
    for row in records:
        name = '{}-t{}-p{}-{}'.format(row['mesh'], row['threads'], row['pack'],
                                     'check' if row['verify'] else 'timing')
        case = directory / 'raw/study' / name
        command = json.loads((case / 'command.json').read_text())
        require(command == {k: v for k, v in row.items() if k != 'result'},
                'capture command differs from records')
        require(row['binary_sha256'] == binaries['build/cvfem/cvfem_hex8_unstructured_bench']
                and row['memory_policy'] == 'THP disabled', 'binary or memory policy differs')
        identity = row['identity']
        require(identity == identities.setdefault(row['mesh'], identity), 'mesh identity changed')
        text = (case / 'run.log').read_text()
        require('THP_LAUNCH policy=disabled disabled=1 ' in text, 'missing policy readback')
        require(study.check(text, identity, row['threads'], row['pack'], 12, 12,
                            row['verify']) == row['result'], 'raw capture differs from records')
    require(study.summary(records) == (directory / 'raw/study/summary.md').read_text(),
            'saved summary differs from raw captures')
    return records


def ratios(row, operator):
    samples = {(int(s['block']), s['layout']): float(s['seconds'])
               for s in row['result']['samples'] if s['op'] == operator}
    atomic = [samples[b, 'atomic'] for b in range(12)]
    packed = [samples[b, 'packed'] for b in range(12)]
    paired = [a / p for a, p in zip(atomic, packed)]
    return statistics.mean(atomic) / statistics.mean(packed), min(paired), max(paired)


def outputs(records):
    rows = {(r['mesh'], r['pack']): r for r in records
            if not r['verify'] and r['threads'] == 72}
    table = [PREAMBLE, r'\begin{tabular}{@{}lrrr@{}}', r'\toprule',
             r'Mesh & Pack & $\Fres$ ratio [range] & $\Jex$ ratio [range] \\', r'\midrule']
    for mesh, label in (('medium', 'M'), ('large', 'L')):
        for pack in (256, 1024):
            cells = [label, str(pack)]
            for op in ('residual', 'jacobian'):
                cells.append('{:.3f} [{:.3f}, {:.3f}]'.format(*ratios(rows[mesh, pack], op)))
            table.append(' & '.join(cells) + r' \\')
    values = dict(Job='5052301', Host='nid006545', Threads=72, Blocks=12, Repeat=12, Warmup=10)
    for mesh, label in (('medium', 'Medium'), ('large', 'Large')):
        row = rows[mesh, 256]
        values[label + 'Cells'] = row['identity']['elements']
    row = rows['medium', 1024]
    values['MediumBigPacks'] = (row['identity']['elements'] + 1023) // 1024
    values['MediumBigSlowdown'] = '{:.1f}'.format(100 * (1 / ratios(row, 'jacobian')[0] - 1))
    macros = PREAMBLE + ''.join(r'\newcommand{\unstr%s}{%s}' % (k, v) + '\n'
                               for k, v in values.items())
    return '\n'.join(table + [r'\bottomrule', r'\end{tabular}', '']), macros


def build(data, figures, tables):
    table, macros = outputs(read_study(Path(data) / DATASET))
    files = [(Path(tables) / 'unstructured.tex', table),
             (Path(figures) / 'unstructured_macros.tex', macros)]
    for path, text in files:
        path.write_text(text)
    return [str(p) for p, _ in files]


def selftest(data):
    directory = Path(data) / DATASET
    rows = read_study(directory)
    table, macros = outputs(rows)
    assert '0.924 [0.917, 0.929]' in table
    assert '1.028 [0.998, 1.175]' in table
    assert r'\unstrMediumBigSlowdown}{8.3}' in macros
    # The paper must retain both the slow case and any failed capture.
    with tempfile.TemporaryDirectory() as temporary:
        copy = Path(temporary) / DATASET
        shutil.copytree(str(directory), str(copy))
        record = copy / 'raw/study/records.json'
        original = record.read_bytes()
        manifest = copy / 'RAW-SHA256.txt'
        original_manifest = manifest.read_text()
        for content, refresh_hash in ((b'[]', False), (json.dumps(rows[:-1]).encode(), True)):
            record.write_bytes(content)
            if refresh_hash:
                manifest.write_text(original_manifest.replace(
                    hashlib.sha256(original).hexdigest(), hashlib.sha256(content).hexdigest()))
            try:
                read_study(copy)
            except ValueError:
                pass
            else:
                raise AssertionError('changed or missing records accepted')
        record.write_bytes(original)
    return True

