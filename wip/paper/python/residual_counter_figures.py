"""Generate the residual counter table from the accepted, archived Grace campaign."""
import hashlib
import json
from pathlib import Path
import statistics
import sys
import tarfile

ROOT = Path(__file__).resolve().parents[3]
SCRIPTS = ROOT / 'spikes/cvfem/scripts'
sys.path.insert(0, str(SCRIPTS))
import roofline_operator as operator
import roofline_reuse_diagnostic as reuse
from roofline_calibration import counter_events, parse_perf
from roofline_sweep_validation import window_seconds
from roofline_warmup_diagnostic import parse_output as parse_control

PREAMBLE = '% Generated by python/residual_counter_figures.py via make figures; do not edit.\n'


def read_study(directory):
    directory = Path(directory)
    meta = json.loads((directory/'provenance.json').read_text())
    if Path(meta['archive']).name != meta['archive']:
        raise ValueError('counter archive must be a local file')
    archive = directory/meta['archive']
    if hashlib.sha256(archive.read_bytes()).hexdigest() != meta['sha256']:
        raise ValueError('counter archive hash mismatch')
    with tarfile.open(archive, 'r:gz') as tar:
        members = tar.getmembers()
        if len(members) != meta['archive_files'] or len({m.name for m in members}) != len(members):
            raise ValueError('incomplete or duplicate counter archive')
        if any(not m.isfile() or Path(m.name).is_absolute() or '..' in Path(m.name).parts for m in members):
            raise ValueError('invalid counter archive entry')
        files = {m.name: tar.extractfile(m).read() for m in members}
    def data(name):
        return json.loads(files[name])
    def text(name):
        return files[name].decode()
    for module, folder in ((operator, 'study'), (reuse, 'study/calibration')):
        name = Path(module.__file__).name
        if files[folder+'/'+name] != Path(module.__file__).read_bytes():
            raise ValueError('captured counter analysis changed: '+name)
    for name in ('roofline_calibration.py','roofline_sweep_validation.py','roofline_warmup_diagnostic.py'):
        if files['study/calibration/'+name] != (SCRIPTS/name).read_bytes():
            raise ValueError('captured counter parser changed: '+name)
    for folder in ('study/operators', 'study/calibration/captures'):
        for name, digest in data(folder+'/files.sha256.json').items():
            if Path(name).name != name or hashlib.sha256(files[folder+'/'+name]).hexdigest() != digest:
                raise ValueError('counter capture hash mismatch: '+name)
    folder = 'study/operators'
    topo = data(folder+'/topology.json')
    expected = dict(job='5039102',host='nid006550',threads=72,n=128,pack_size=1024,
                    precision='fp64',geometry='affine',rhie_chow=True,state_gradients='cached',boundary=False,transient=False)
    if any(meta.get(k) != v for k,v in expected.items()) or any(topo[k] != meta[k] for k in ('job','host')):
        raise ValueError('counter provenance/scope mismatch')
    controls_folder = 'study/calibration/captures'
    if topo != data(controls_folder+'/topology.json') or topo['cpus'] != list(range(72)) or topo['node'] != 0:
        raise ValueError('controls and operators differ in allocation or binding')
    if data(controls_folder+'/collection.json') != dict(mode='reuse-validation',elements=80000000):
        raise ValueError('missing reuse control validation')
    controls = data(controls_folder+'/records.json')
    control_report, ok = reuse.analyze_measurements(controls,80000000,True)
    if not ok or control_report != text(controls_folder+'/summary.txt'):
        raise ValueError('control validation failed')
    scf, core = counter_events(topo)
    scf += [topo['pmu']+'/'+e+'/' for e in ('cmem_wb_data','cmem_wr_data')]
    records = data(folder+'/records.json')
    for rows, base, is_control in ((controls,controls_folder,True),(records,folder,False)):
        for r in rows:
            if is_control:
                stem = '{}/{}-{}-b{}-r{}-reuse'.format(base,r['mode'],r['kind'],r['block'],r['repeat'])
                parsed = parse_control(text(stem+'.out'),r['mode'],80000000,r['repeat'],r['kind'],30)
            else:
                stem = '{}/{}-{}-{}-b{}-r{}'.format(base,r['scheme'],r['layout'],r['kind'],r['block'],r['repeat'])
                parsed = operator.parse_output(text(stem+'.out'),r['scheme'],r['layout'],r['kind'],r['repeat'],warmup=30)
            if any(r[k] != v for k,v in parsed.items()):
                raise ValueError('counter record differs from checked output')
            if r['kind'] != 'normal':
                memory, floating = text(stem+'.scf.perf'), text(stem+'.core.perf')
                m, f = parse_perf(memory,scf), parse_perf(floating,core)
                parsed = dict(read_bytes=32*m[scf[0]],write_bytes=m[scf[1]],fp_ops=sum(f.values()),
                              component_write_bytes=32*m[scf[2]]+m[scf[3]],
                              scf_seconds=window_seconds(memory,scf,1),core_seconds=window_seconds(floating,core,72))
                if any(r[k] != v for k,v in parsed.items()):
                    raise ValueError('counter record differs from raw event counts')
    report, ok = operator.analyze(records)
    reference = text(folder+'/control-reference.txt')
    if not ok or reference+'\n'+report != text(folder+'/summary.txt'):
        raise ValueError('operator campaign failed')
    return meta, records, controls


def metrics(records, scheme, layout):
    rows = [r for r in records if r['scheme']==scheme and r['layout']==layout]
    normal = [1000*r['seconds']/r['repeat'] for r in rows if r['kind']=='normal']
    sweep = [r for r in rows if r['kind']=='sweep']
    return dict(normal=statistics.mean(normal),normal_min=min(normal),normal_max=max(normal),
                mb=statistics.mean((r['read_bytes']+r['write_bytes'])/r['repeat']/1e6 for r in sweep),
                gbps=statistics.mean((r['read_bytes']+r['write_bytes'])/r['seconds']/1e9 for r in sweep),
                fp=statistics.mean(r['fp_ops']/r['repeat']/1e9 for r in sweep))


def table(records):
    lines = [PREAMBLE, r'\begin{tabular}{@{}llrrrr@{}}', r'\toprule',
             r'Scheme & Layout & ms & MB & GB/s & Gop \\', r'\midrule']
    for scheme, label in (('fo','First-order'),('darwish','Darwish')):
        for layout in ('atomic','packed'):
            m = metrics(records,scheme,layout)
            lines.append(f"{label} & {layout} & {m['normal']:.2f} & {m['mb']:.1f} & {m['gbps']:.1f} & {m['fp']:.2f}"+r' \\')
    return '\n'.join(lines+[r'\bottomrule',r'\end{tabular}',''])


def macros(meta, records, controls):
    lines = [PREAMBLE]
    def put(name, value):
        lines.append(r'\newcommand{\counter%s}{%s}' % (name,value))
    for name in ('job','host','n','threads','pack_size'):
        put(''.join(word.capitalize() for word in name.split('_')),meta[name])
    for scheme, label in (('fo','Fo'),('darwish','Darwish')):
        a,p = (metrics(records,scheme,layout) for layout in ('atomic','packed'))
        put(label+'Speedup',f"{a['normal']/p['normal']:.2f}")
        put(label+'TrafficChange',f"{100*(p['mb']/a['mb']-1):+.2f}")
        for layout,m in (('Atomic',a),('Packed',p)):
            put(label+layout+'Time',f"{m['normal']:.2f}")
    for mode in ('copy','triad'):
        rates = [(r['read_bytes']+r['write_bytes'])/r['seconds']/1e9 for r in controls if r['mode']==mode and r['kind']=='sweep']
        put(mode.capitalize()+'Bandwidth',f'{statistics.mean(rates):.1f}')
    return '\n'.join(lines)+'\n'


def build(data, figures, tables):
    meta, records, controls = read_study(Path(data)/'residual_counters_5039102')
    outputs = [(Path(figures)/'residual_counter_macros.tex', macros(meta,records,controls)),
               (Path(tables)/'residual_counters.tex', table(records))]
    for path, content in outputs:
        path.write_text(content)
    return [str(path) for path, _ in outputs]


def selftest():
    import tempfile
    directory = ROOT/'wip/paper/data/residual_counters_5039102'
    meta, records, controls = read_study(directory)
    assert r'\counterFoSpeedup}{1.94}' in macros(meta,records,controls)
    assert r'\counterDarwishSpeedup}{1.42}' in macros(meta,records,controls)
    with tempfile.TemporaryDirectory() as temp:
        path=Path(temp)
        (path/meta['archive']).symlink_to(directory/meta['archive'])
        altered=dict(meta,sha256='0'*64)
        (path/'provenance.json').write_text(json.dumps(altered))
        try:read_study(path)
        except ValueError:pass
        else:raise AssertionError('modified counter archive accepted')
        altered=dict(meta,host='different')
        (path/'provenance.json').write_text(json.dumps(altered))
        try:read_study(path)
        except ValueError:pass
        else:raise AssertionError('different counter host accepted')
    return True
