PREAMBLE = "% Generated by python/scatter_figures.py via make figures; do not edit.\n"

ARCHIVE_NAME = "pasc27-scatter-5026072.zip"
ARCHIVE_SHA256 = "1b34fdb16838fc53d455d9d61b1cd74b813aae117f961b9f907ca53b0b14945e"
EVIDENCE_COMMIT = "9ce344db3a1b08bea273f97c9f16d84aa553ae07"
EVIDENCE_DIRECTORY = "wip/paper/data/scatter_5026072"
EVIDENCE_FILES = sorted(
    [f"{layout}-{scheme}-t{threads}.out"
     for layout in ("atomic", "packed") for scheme in ("fo", "darwish") for threads in (1, 72)]
    + ["binary.sha256", "environment.out", "provenance.json", "source-changes.patch",
       "source-manifest.sha256", "source-revisions.txt", "verification.out"])


def read_archive(path, expected_sha256=ARCHIVE_SHA256):
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(
            f"Missing scatter evidence archive: {path}. Set SFEM_SCATTER_ARCHIVE or run "
            "python3 python/scatter_figures.py --recover-archive-from-git; see README.md.")
    payload = path.read_bytes()
    if hashlib.sha256(payload).hexdigest() != expected_sha256:
        raise ValueError("scatter archive SHA256 mismatch")
    with zipfile.ZipFile(io.BytesIO(payload)) as archive, tempfile.TemporaryDirectory() as tmp:
        expected = {"scatter_5026072/" + name for name in EVIDENCE_FILES}
        names = archive.namelist()
        if len(names) != len(expected) or set(names) != expected:
            raise ValueError("scatter archive has missing, extra or duplicate members")
        directory = Path(tmp)
        for name in EVIDENCE_FILES:
            # Write only the named files; archive paths never choose the destination.
            (directory / name).write_bytes(archive.read("scatter_5026072/" + name))
        return read_study(directory)


def recover_archive_from_git(destination):
    """Recover the unchanged evidence from the original review commit, without network access."""
    destination = Path(destination)
    if destination.exists():
        read_archive(destination)
        return
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_STORED) as archive:
        for name in EVIDENCE_FILES:
            payload = subprocess.check_output(
                ["git", "-C", str(ROOT), "show", f"{EVIDENCE_COMMIT}:{EVIDENCE_DIRECTORY}/{name}"])
            info = zipfile.ZipInfo("scatter_5026072/" + name)
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            archive.writestr(info, payload)
    payload = buffer.getvalue()
    if hashlib.sha256(payload).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("recovered scatter archive SHA256 mismatch; no archive written")
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("xb") as output:
        output.write(payload)


def read_study(directory):
    directory = Path(directory)
    meta = json.loads((directory / "provenance.json").read_text())
    for name, digest in meta["files_sha256"].items():
        if Path(name).name != name:
            raise ValueError("scatter provenance must name local files")
        if hashlib.sha256((directory / name).read_bytes()).hexdigest() != digest:
            raise ValueError(f"scatter provenance mismatch: {name}")
    if not re.fullmatch(r"[A-Za-z0-9]+", meta["host"]):
        raise ValueError("invalid scatter host")
    environment = (directory / "environment.out").read_text().splitlines()
    if meta["host"] not in environment or f"SLURM_JOB_ID={meta['job']}" not in environment:
        raise ValueError("scatter host/job disagrees with recorded environment")
    if (directory / "binary.sha256").read_text().split()[0] != meta["binary_sha256"]:
        raise ValueError("scatter binary hash disagrees with recorded build")
    cases = {}
    for threads in (1, 72):
        for ho, scheme in ((0, "fo"), (1, "darwish")):
            for layout in ("atomic", "packed"):
                name = f"{layout}-{scheme}-t{threads}.out"
                if name not in meta["files_sha256"]:
                    raise ValueError(f"unbound scatter log: {name}")
                path = directory / name
                config, rows = analysis.read_case(path)
                lines = path.read_text().splitlines()
                command = shlex.split(lines[0])
                for flag, key in (("--n", "n"), ("--pack-size", "pack_size"),
                                  ("--repeat", "repeat"), ("--warmup", "warmup"),
                                  ("--scatter-samples", "samples")):
                    if int(command[command.index(flag) + 1]) != meta[key]:
                        raise ValueError(f"{name}: inconsistent {flag}")
                if "--rhie-chow" not in command or "--scatter-study" not in command:
                    raise ValueError(f"{name}: missing study or RC flag")
                expected = dict(layout=layout, threads=threads, ho=ho,
                                limiter=3 if ho else 0, elements=meta["n"]**3,
                                nodes=(meta["n"]+1)**3, repeat=meta["repeat"],
                                warmup=meta["warmup"], samples=meta["samples"])
                if any(config[k] != str(v) for k, v in expected.items()):
                    raise ValueError(f"{name}: inconsistent case")
                capture = (f"scatter_capture entries={32*meta['n']**3} "
                           "finite=1 nonzero=1 identical=1 bypass_zero=1")
                if lines.count(capture) != 1:
                    raise ValueError(f"{name}: missing contribution check")
                for field in range(4):
                    prefix = f"scatter_equivalence field={field} "
                    found = [s for s in lines if s.startswith(prefix)]
                    if len(found) != 1:
                        raise ValueError(f"{name}: missing equation check")
                    fields = dict(s.split("=") for s in found[0].split()[1:])
                    error, tolerance = float(fields["relative"]), float(fields["tolerance"])
                    if tolerance != 1e-11 or not 0 <= error <= tolerance:
                        raise ValueError(f"{name}: failed equation check")
                cases[threads, ho, layout] = rows
    return meta, cases


def averages(rows):
    return [statistics.mean(row[i] for row in rows) * 1000 for i in range(3)]


def table(cases):
    out = [PREAMBLE, r"\begin{tabular}{@{}rllrrrlrr@{}}", r"\toprule",
           r"Threads & Scheme & Layout & $t_0$ & $t_+$ & $t_-$ & $\Delta$ [min, max] & \% full & \% ctrl. \\",
           r"\midrule"]
    for threads in (1, 72):
        if threads == 72:
            out.append(r"\midrule")
        for ho, scheme in ((0, "first-order"), (1, "Darwish")):
            for layout in ("atomic", "packed"):
                rows = cases[threads, ho, layout]
                normal, full, bypass = averages(rows)
                delta = [(row[1]-row[2])*1000 for row in rows]
                mean = statistics.mean(delta)
                out.append(
                    f"{threads} & {scheme} & {layout} & {normal:.3f} & {full:.3f} & "
                    f"{bypass:.3f} & {mean:.3f} [{min(delta):.3f}, {max(delta):.3f}] & "
                    f"{100*mean/full:.1f} & {100*(full/normal-1):+.2f}" + r" \\")
    return "\n".join(out + [r"\bottomrule", r"\end{tabular}", ""])


def macros(meta, cases):
    out = [PREAMBLE]
    def put(name, value):
        out.append(r"\newcommand{\scatter%s}{%s}" % (name, value))
    for key in ("n", "pack_size", "repeat", "warmup", "samples", "job", "host"):
        put("".join(word.capitalize() for word in key.split("_")), meta[key])
    overhead = []
    for rows in cases.values():
        normal, full, _ = averages(rows)
        overhead.append(100*(full/normal-1))
    put("OverheadMin", f"{min(overhead):+.2f}")
    put("OverheadMax", f"{max(overhead):+.2f}")
    for ho, tag in ((0, "Fo"), (1, "Ho")):
        a = averages(cases[72, ho, "atomic"])
        p = averages(cases[72, ho, "packed"])
        for layout, times in (("Atomic", a), ("Packed", p)):
            put(tag+layout+"Delta", f"{times[1]-times[2]:.3f}")
        put(tag+"GapShare", f"{100*((a[1]-a[2])-(p[1]-p[2]))/(a[1]-p[1]):.1f}")
        put(tag+"NormalSpeedup", f"{a[0]/p[0]:.2f}")
    return "\n".join(out) + "\n"


def build(data, figures, tables):
    archive = os.environ.get("SFEM_SCATTER_ARCHIVE", str(Path(data) / ARCHIVE_NAME))
    meta, cases = read_archive(archive)
    outputs = [(Path(figures)/"scatter_macros.tex", macros(meta, cases)),
               (Path(tables)/"scatter.tex", table(cases))]
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return [str(path) for path, _ in outputs]

def selftest():
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        directory = Path(tmp)
        meta = dict(n=2, pack_size=8, repeat=1, warmup=1, samples=6,
                    job=1, host="fixture", binary_sha256="0"*64, files_sha256={})
        def write(name, text):
            (directory/name).write_text(text)
            meta["files_sha256"][name] = hashlib.sha256(text.encode()).hexdigest()
            (directory/"provenance.json").write_text(json.dumps(meta))
        write("environment.out", "fixture\nSLURM_JOB_ID=1\n")
        write("binary.sha256", "0"*64 + "  fixture\n")
        for threads in (1, 72):
            for ho, scheme in ((0, "fo"), (1, "darwish")):
                for layout in ("atomic", "packed"):
                    full = 4 if layout == "atomic" else 2
                    name = f"{layout}-{scheme}-t{threads}.out"
                    lines = [
                        "/fixture --n 2 --pack-size 8 --repeat 1 --warmup 1 --scatter-samples 6 --rhie-chow --scatter-study",
                        "scatter_capture entries=256 finite=1 nonzero=1 identical=1 bypass_zero=1"]
                    lines += [f"scatter_equivalence field={f} relative=0 tolerance=1e-11" for f in range(4)]
                    lines += ["scatter_gate PASS",
                              f"scatter_config layout={layout} threads={threads} ho={ho} limiter={3 if ho else 0} "
                              "elements=8 nodes=27 repeat=1 warmup=1 samples=6"]
                    lines += [f"scatter_sample {i} {full} {full} 1" for i in range(6)]
                    lines += ["scatter_study PASS"]
                    write(name, "\n".join(lines)+"\n")
        parsed_meta, cases = read_study(directory)
        assert r"\scatterFoGapShare}{100.0}" in macros(parsed_meta, cases)
        assert r"\scatterHoNormalSpeedup}{2.00}" in macros(parsed_meta, cases)
        cases[1, 0, "atomic"] = [(1, 1, 2)]*6
        assert "-1000.000 [-1000.000, -1000.000]" in table(cases)
        name = "atomic-fo-t1.out"
        original = (directory/name).read_text()
        changes = [
            ("bypass_zero=1", "bypass_zero=0"),
            ("relative=0", "relative=nan"),
            ("scatter_gate PASS", "scatter_gate FAIL"),
            ("scatter_sample 5", "scatter_sample 4"),
            ("4 4 1", "4 4 nan"),
            ("threads=1", "threads=2"),
            ("--n 2", "--n 3"),
        ]
        for old, new in changes:
            write(name, original.replace(old, new))
            try:
                read_study(directory)
            except ValueError:
                pass
            else:
                raise AssertionError(f"accepted invalid scatter data: {new}")
        write(name, original)
        (directory/name).write_text(original+"\n")
        try:
            read_study(directory)
        except ValueError:
            pass
        else:
            raise AssertionError("accepted modified data without updated hash")
        write(name, original)
        for name in EVIDENCE_FILES:
            if not (directory / name).exists():
                write(name, "fixture\n")
        archive_path = directory / "fixture.zip"
        with zipfile.ZipFile(archive_path, "w") as archive:
            for name in EVIDENCE_FILES:
                archive.write(directory / name, "scatter_5026072/" + name)
        digest = hashlib.sha256(archive_path.read_bytes()).hexdigest()
        _, archived_cases = read_archive(archive_path, digest)
        assert len(archived_cases) == 8
        try:
            read_archive(archive_path, "0" * 64)
        except ValueError:
            pass
        else:
            raise AssertionError("accepted an altered archive")
        with zipfile.ZipFile(archive_path, "a") as archive:
            archive.writestr("../unexpected", "fixture")
        digest = hashlib.sha256(archive_path.read_bytes()).hexdigest()
        try:
            read_archive(archive_path, digest)
        except ValueError:
            pass
        else:
            raise AssertionError("accepted an unexpected archive member")
        try:
            read_archive(directory / "missing.zip")
        except FileNotFoundError:
            pass
        else:
            raise AssertionError("accepted missing evidence")
    return True


