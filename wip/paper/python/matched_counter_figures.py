"""Generate tables and companion figures after replaying the matched Grace campaign."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tarfile
import tempfile
import matched_roofline

HERE = Path(__file__).resolve().parent
PREAMBLE = '% Generated by python/matched_counter_figures.py; do not edit.\n'


def unpack(directory, target):
    meta = json.loads((directory/'provenance.json').read_text())
    expected = dict(job='5047137',host='nid006550',threads=72,n=128,pack_size=1024,
                    precision='fp64',geometry='affine',rhie_chow=True,state_gradients='cached',
                    direction='coordinate_fixed',boundary=False,transient=False,thp='disabled')
    if any(meta.get(key) != value for key,value in expected.items()):
        raise ValueError('matched campaign provenance/scope differs')
    if Path(meta['archive']).name != meta['archive']:
        raise ValueError('archive must be a local file')
    archive = directory/meta['archive']
    if hashlib.sha256(archive.read_bytes()).hexdigest() != meta['sha256']:
        raise ValueError('matched campaign archive hash differs')
    with tarfile.open(archive, 'r:gz') as tar:
        members = tar.getmembers()
        if len(members) != meta['archive_files'] or len({m.name for m in members}) != len(members):
            raise ValueError('incomplete or duplicate matched archive')
        for member in members:
            if not member.isfile() or Path(member.name).is_absolute() or '..' in Path(member.name).parts:
                raise ValueError('invalid archive entry')
            path = target/member.name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(tar.extractfile(member).read())
    return meta


def replay(directory):
    # Isolate captured imports from the older campaign's frozen analysis.
    result = subprocess.run([sys.executable, str(HERE/'verify_matched_counters.py'), str(directory)],
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
    if result.returncode:
        raise ValueError('matched campaign verification failed: '+result.stderr)
    return json.loads(result.stdout)


def read_study(directory):
    with tempfile.TemporaryDirectory() as temporary:
        path = Path(temporary)
        meta = unpack(Path(directory), path)
        return meta, replay(path)


def tables(result):
    metrics = result['metrics']
    residual = [PREAMBLE, r'\begin{tabular}{@{}llrrrr@{}}',r'\toprule',
                r'Scheme & Layout & ms & MB & GB/s & Gop \\',r'\midrule']
    for scheme,label in (('fo','First-order'),('darwish','Darwish')):
        for layout in ('atomic','packed'):
            value = metrics['residual-'+scheme+'-'+layout]
            residual.append('{} & {} & {:.2f} & {:.1f} & {:.1f} & {:.2f}'.format(
                label,layout,value['normal_ms'],value['mb'],value['gbps'],value['gop'])+r' \\')
    actions = [PREAMBLE, r'\begin{tabular}{@{}llrrrr@{}}',r'\toprule',
               r'Operator & Layout & ms/apply [range] & MB/apply & GB/s & Gop/s \\',r'\midrule']
    for operation,scheme,label in (('jacobian','fo',r'$\Jex$'),('jacobian','darwish',r'$\Jhoex$ (Darwish)'),
                                   ('lagged','fo',r'$\Jlag$'),('spmv','fo',r'$\Jlag$ (SpMV)')):
        for layout in (('packed',) if operation == 'spmv' else ('atomic','packed')):
            value = metrics['-'.join((operation,scheme,layout))]
            low,high = value['normal_range']
            actions.append('{} & {} & {:.2f} [{:.2f}, {:.2f}] & {:.1f} & {:.1f} & {:.1f}'.format(
                label,'BSR' if operation=='spmv' else layout,value['normal_ms'],low,high,value['mb'],value['gbps'],value['gops'])+r' \\')
    return ('\n'.join(residual+[r'\bottomrule',r'\end{tabular}','']),
            '\n'.join(actions+[r'\bottomrule',r'\end{tabular}','']))


def macros(meta, result):
    metrics = result['metrics']
    values = dict(Job=meta['job'],Host=meta['host'],N=meta['n'],Threads=meta['threads'],PackSize=meta['pack_size'])
    for scheme,label in (('fo','Fo'),('darwish','Darwish')):
        atomic,packed = (metrics['residual-'+scheme+'-'+layout] for layout in ('atomic','packed'))
        values[label+'Speedup'] = '{:.2f}'.format(atomic['normal_ms']/packed['normal_ms'])
        values[label+'TrafficChange'] = '{:+.2f}'.format(100*(packed['mb']/atomic['mb']-1))
        values['Jac'+label+'Speedup'] = '{:.2f}'.format(metrics['jacobian-'+scheme+'-atomic']['normal_ms']/metrics['jacobian-'+scheme+'-packed']['normal_ms'])
    for mode in ('copy','triad'):
        values[mode.capitalize()+'Bandwidth'] = '{:.1f}'.format(metrics[mode]['gbps'])
    values['GemmUseful'] = '{:.0f}'.format(metrics['dgemm']['useful_gflops'])
    values['GemmSpeculative'] = '{:.0f}'.format(metrics['dgemm']['speculative_gops'])
    lagged,spmv = (metrics[name] for name in ('lagged-fo-packed','spmv-fo-packed'))
    values['LaggedSpmv'] = '{:.2f}'.format(spmv['normal_ms']/lagged['normal_ms'])
    values['LaggedAtomic'] = '{:.2f}'.format(metrics['lagged-fo-atomic']['normal_ms']/lagged['normal_ms'])
    values['TrafficSpmvLagged'] = '{:.2f}'.format(spmv['mb']/lagged['mb'])
    values['LaggedSeconds'] = '{:.2f}'.format(lagged['normal_ms'])
    values['SpmvSeconds'] = '{:.2f}'.format(spmv['normal_ms'])
    values['ExactLagged'] = '{:.2f}'.format(metrics['jacobian-fo-packed']['normal_ms']/lagged['normal_ms'])
    return PREAMBLE+''.join(r'\newcommand{\matched%s}{%s}'%(key,value)+'\n' for key,value in values.items())


def build(data, figures, table_dir):
    meta, result = read_study(Path(data)/'matched_counters_5047137')
    residual,actions = tables(result)
    outputs = [(Path(figures)/'matched_counter_macros.tex',macros(meta,result)),
               (Path(table_dir)/'matched_residuals.tex',residual),(Path(table_dir)/'matched_actions.tex',actions)]
    outputs.extend(matched_roofline.build_outputs(meta, result, Path(figures).parent/'reproducibility'))
    for path,text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return [str(path) for path,text in outputs]


def selftest():
    directory = HERE.parent/'data/matched_counters_5047137'
    with tempfile.TemporaryDirectory() as temporary:
        path = Path(temporary)
        meta = unpack(directory, path)
        result = replay(path)
        assert result['numerical_checks'] == 3240
        assert r'\matchedLaggedSpmv}{2.98}' in macros(meta,result)
        assert '19.37 [19.34, 19.40]' in tables(result)[1]
        assert matched_roofline.selftest(meta, result)
        for name in ('records.json','spmv-fo-packed-sweep-b0-r30.scf.perf',
                     'spmv-fo-packed-sweep-b0-r30.policy-after.json','spmv-fo-packed-b0-reuse.ready.out'):
            folder = path/'study/actions'
            file = folder/name
            original = file.read_bytes()
            manifest = folder/'files.sha256.json'
            before = manifest.read_bytes()
            if name == 'records.json':
                rows = json.loads(original); rows.pop(); file.write_text(json.dumps(rows))
            elif name.endswith('.perf'):
                file.write_text(original.decode().replace('100.00','50.00'))
            elif name.endswith('.json'):
                observation=json.loads(original); observation['thp_enabled']=1; file.write_text(json.dumps(observation))
            else:
                file.write_text(original.decode().replace('source=coordinates','source=numbering'))
            hashes=json.loads(before); hashes[name]=hashlib.sha256(file.read_bytes()).hexdigest(); manifest.write_text(json.dumps(hashes))
            try:
                replay(path)
            except ValueError:
                pass
            else:
                raise AssertionError('invalid matched evidence accepted: '+name)
            file.write_bytes(original); manifest.write_bytes(before)
    return True
