"""Generate the MMS paragraph values and supporting table from both Grace jobs."""
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import tempfile


PAPER = Path(__file__).resolve().parents[1]
DATASET = 'mms_5077906'


def read_study(data):
    directory = Path(data)/DATASET
    spec = importlib.util.spec_from_file_location('combined_mms_verification', directory/'verify.py')
    verify = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(verify)
    result = verify.check(directory)
    if result != json.loads((directory/'verification.json').read_text()):
        raise ValueError('stored MMS verification differs from raw replay')
    for scheme in ('lo', 'ho_lim0', 'ho_lim1', 'ho_lim2_k0', 'ho_lim3'):
        ladder = [r for r in result['rows'] if r['scheme'] == scheme]
        if any(a[key] <= b[key] for a, b in zip(ladder, ladder[1:]) for key in ('u_l2', 'u_linf')):
            raise ValueError('MMS errors do not decrease as the paper states')
    return result


def outputs(result):
    fine = [r for r in result['rows'] if r['n'] == 40]
    reconstructed = [r for r in fine if r['scheme'] != 'lo']
    if not all(r['absolute_accuracy_pass'] for r in reconstructed) or fine[0]['absolute_accuracy_pass']:
        raise ValueError('fine-grid accuracy verdicts differ from the paragraph')
    values = dict(Grids=4, Cases=result['cases'], FineN=40, AccuracyTol='0.01',
                  ReconstructedMinRate='{:.2f}'.format(min(r['adjacent_velocity_l2_rate'] for r in reconstructed)),
                  ReconstructedMaxRate='{:.2f}'.format(max(r['adjacent_velocity_l2_rate'] for r in reconstructed)))
    macros = '% Generated by python/mms_refinement.py; do not edit.\n'
    macros += ''.join(r'\newcommand{\mms%s}{%s}' % (k, v) + '\n' for k, v in values.items())
    lines = ['<!-- Generated by python/mms_refinement.py; do not edit. -->',
             '# Grace MMS refinement', '',
             'Steady affine Farrell MMS on [0,2]^3; FP64, eight configured threads, density 1 and viscosity 0.01.',
             'Manufactured velocity on all faces; zero-mean pressure; unfrozen convection and exact Rhie--Chow derivatives.',
             'FGMRES/block Jacobi, restart 480; final nonlinear relative tolerance 1e-10, linear tolerance 1e-6.',
             'Jobs 5077627 (n=16/24/32) and 5077906 (n=40) use the identical solver binary.', '',
             '| Scheme | n | Velocity L2 | Shifted pressure L2 | Velocity max | Fixed 0.01 gate | Adjacent velocity L2 rate |',
             '|---|---:|---:|---:|---:|---|---:|']
    names = dict(lo='First-order', ho_lim0='Unlimited', ho_lim1='Clip',
                 ho_lim2_k0='Venkatakrishnan K=0', ho_lim3='Darwish')
    for row in result['rows']:
        rate = row['adjacent_velocity_l2_rate']
        lines.append('| {} | {} | {:.7g} | {:.7g} | {:.7g} | {} | {} |'.format(
            names[row['scheme']], row['n'], row['u_l2'], row['p_l2_shifted'], row['u_linf'],
            'PASS' if row['absolute_accuracy_pass'] else 'FAIL', '-' if rate is None else '{:.4f}'.format(rate)))
    lines += ['', 'All twenty final nonlinear targets are met. Four fixed accuracy targets pass at n=40; all sixteen failed targets and original exits remain visible.',
              'Clip at n=16 accepts an intermediate continuation residual floor, then meets the final nonlinear target.',
              'Rates use physical spacing h=2/n. These observations do not establish a common asymptotic order, an unstructured solve or a performance comparison.', '',
              'Raw evidence: [16/24/32 archive](../data/mms_5077627/README.md), [n=40 and combined replay](../data/mms_5077906/README.md).', '']
    return macros, '\n'.join(lines)


def build(data, figures, documentation):
    macros, table = outputs(read_study(data))
    files = [(Path(figures)/'mms_macros.tex', macros),
             (Path(documentation)/'mms-refinement.md', table)]
    for path, text in files:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return [str(path) for path, _ in files]


def selftest():
    result = read_study(PAPER/'data')
    macros, table = outputs(result)
    if r'\mmsReconstructedMinRate}{1.36}' not in macros or table.count('| PASS |') != 4 or table.count('| FAIL |') != 16:
        raise ValueError('MMS display loses a result or rate')
    with tempfile.TemporaryDirectory() as name:
        root = Path(name)
        for dataset in ('mms_5077627', DATASET):
            shutil.copytree(PAPER/'data'/dataset, root/dataset, ignore=shutil.ignore_patterns('__pycache__'))
        changes = [
            ('raw/settings.txt', 'SFEM_VERIFY_TOL=0.01', 'SFEM_VERIFY_TOL=0.1'),
            ('raw/BUILD-SHA256.txt', 'cfd304b95e44292685970128b6311c3c95f55bd725232639cd2405659b092162', '0'*64),
            ('raw/study/conv_ho_lim0_n40.log', '8.564342e-03', '8.564342e-02'),
        ]
        manifest = root/DATASET/'RAW-SHA256.txt'
        initial_manifest = manifest.read_text()
        for relative, old, new in changes:
            path = root/DATASET/relative
            initial = path.read_text()
            if old not in initial:
                raise ValueError('test mutation not applied')
            path.write_text(initial.replace(old, new))
            manifest.write_text('\n'.join(
                hashlib.sha256(path.read_bytes()).hexdigest()+'  '+relative if line.endswith('  '+relative) else line
                for line in initial_manifest.splitlines())+'\n')
            try:
                read_study(root)
            except ValueError:
                pass
            else:
                raise ValueError('MMS reader accepted inconsistent evidence: '+relative)
            path.write_text(initial)
            manifest.write_text(initial_manifest)
    return True
